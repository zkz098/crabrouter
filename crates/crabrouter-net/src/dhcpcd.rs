use crate::Result;
use crate::ipv6_pd::resolve_downstream_ipv6_targets;

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct WanLeaseEvent {
    pub source: String,
    pub wan_name: String,
    pub device: String,
    pub event: String,
    #[serde(default)]
    pub ip: Option<String>,
    #[serde(default)]
    pub gateway: Option<String>,
    #[serde(default)]
    pub dns_servers: Vec<String>,
    #[serde(default)]
    pub ifindex: Option<u32>,
    #[serde(default)]
    pub ipv6_addr: Option<String>,
    #[serde(default)]
    pub ipv6_pd_prefix: Option<String>,
}

/// Renders `/etc/dhcpcd.d/crabrouter.conf` (or `/etc/dhcpcd.conf` drop-in) controlling which
/// WAN interfaces `dhcpcd` manages (including `DHCPv6-PD` `/56` or `/60` delegation over DHCP or
/// `PPPoE` `ppp*` links) and preventing it from running DHCP client requests on LAN ports.
pub fn render_dhcpcd_conf(cfg: &RouterConfig) -> String {
    let mut out = String::from(
        "# Generated by crabrouterd — do not edit manually\n\
         duid\n\
         persistent\n\
         vendorclassid\n\
         option domain_name_servers, domain_name, domain_search, host_name\n\
         option classless_static_routes\n\
         option interface_mtu\n\
         nohook resolv.conf\n\n",
    );

    let mut deny: Vec<String> = Vec::new();
    for lan in &cfg.lans {
        deny.push(lan.bridge.clone());
        for port in &lan.ports {
            deny.push(port.clone());
        }
    }
    for wan in &cfg.wans {
        if wan.proto != WanProto::Dhcp {
            deny.push(wan.device.clone());
        }
    }
    if !deny.is_empty() {
        let _ = writeln!(out, "denyinterfaces {}", deny.join(" "));
    }

    let pd_targets = resolve_downstream_ipv6_targets(cfg);
    let mut sla_clauses = String::new();
    for t in &pd_targets {
        let _ = write!(sla_clauses, " {}/{}/64", t.interface, t.subnet_id);
    }

    let mut ppp_unit_idx: usize = 0;
    for wan in &cfg.wans {
        match wan.proto {
            WanProto::Dhcp => {
                let _ = writeln!(out, "\ninterface {}", wan.device);
                let _ = writeln!(out, "    metric {}", wan.metric);
                if wan.ipv6_pd {
                    let prefix_len = wan.ipv6_pd_prefix_len.clamp(48, 64);
                    let _ = writeln!(
                        out,
                        "    ipv6rs\n    ia_na 1\n    ia_pd 2/::/{prefix_len}{sla_clauses}"
                    );
                }
            }
            WanProto::Pppoe => {
                if wan.ipv6_pd {
                    let ppp_iface = format!("ppp{ppp_unit_idx}");
                    let prefix_len = wan.ipv6_pd_prefix_len.clamp(48, 64);
                    let _ = writeln!(out, "\ninterface {ppp_iface}");
                    let _ = writeln!(out, "    metric {}", wan.metric);
                    let _ = writeln!(
                        out,
                        "    ipv6only\n    noipv4\n    ipv6rs\n    ia_pd 2/::/{prefix_len}{sla_clauses}"
                    );
                }
                ppp_unit_idx += 1;
            }
            WanProto::Static => {}
        }
    }

    out
}

/// Renders `/etc/dhcpcd.exit-hook` (sourced by `dhcpcd-run-hooks`) posting IPv4 and IPv6-PD lease
/// changes to `crabrouterd`. Kept under `/etc` because `/usr` is a read-only squashfs on the appliance.
pub fn render_dhcpcd_hook_script(endpoint_url: &str) -> String {
    format!(
        "#!/bin/sh\n\
         # Generated by crabrouterd — dhcpcd IPv4 + DHCPv6-PD hook\n\
         case \"$reason\" in\n\
           BOUND|RENEW|REBIND|REBOOT|EXPIRE|RELEASE|STOP|NOCARRIER|BOUND6|RENEW6|REBIND6|REBOOT6|EXPIRE6|RELEASE6|ROUTERADVERT)\n\
             PD_PREFIX=\"${{new_dhcp6_ia_pd1_prefix1:-}}\"\n\
             PD_LEN=\"${{new_dhcp6_ia_pd1_prefix1_length:-}}\"\n\
             if [ -n \"$PD_PREFIX\" ] && [ -n \"$PD_LEN\" ]; then\n\
               case \"$PD_PREFIX\" in\n\
                 */*) ;;\n\
                 *) PD_PREFIX=\"$PD_PREFIX/$PD_LEN\" ;;\n\
               esac\n\
             fi\n\
             PAYLOAD=$(printf '{{\"source\":\"dhcpcd\",\"wan_name\":\"%s\",\"device\":\"%s\",\"event\":\"%s\",\"ip\":\"%s\",\"gateway\":\"%s\",\"ipv6_addr\":\"%s\",\"ipv6_pd_prefix\":\"%s\",\"dns_servers\":[]}}' \\\n\
               \"$interface\" \"$interface\" \"$reason\" \"${{new_ip_address:-}}\" \"${{new_routers%% *}}\" \"${{new_dhcp6_ia_na1_ia_addr1:-}}\" \"$PD_PREFIX\")\n\
             if command -v curl >/dev/null 2>&1; then\n\
               curl -fsS -X POST -H 'Content-Type: application/json' -d \"$PAYLOAD\" '{endpoint_url}' >/dev/null 2>&1 || true\n\
             fi\n\
             ;;\n\
         esac\n"
    )
}

/// Writes `dhcpcd` configuration and exit hook script atomically.
pub fn sync_dhcpcd_files(
    cfg: &RouterConfig,
    conf_path: &Path,
    hook_path: &Path,
    endpoint_url: &str,
) -> Result<()> {
    if let Some(parent) = conf_path.parent()
        && !parent.as_os_str().is_empty()
    {
        fs::create_dir_all(parent)?;
    }
    let tmp_conf = conf_path.with_extension("conf.tmp");
    fs::write(&tmp_conf, render_dhcpcd_conf(cfg))?;
    fs::rename(&tmp_conf, conf_path)?;

    if let Some(parent) = hook_path.parent()
        && !parent.as_os_str().is_empty()
    {
        fs::create_dir_all(parent)?;
    }
    fs::write(hook_path, render_dhcpcd_hook_script(endpoint_url))?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let _ = fs::set_permissions(hook_path, fs::Permissions::from_mode(0o755));
    }
    Ok(())
}

/// Triggers `dhcpcd -n <iface>` to rebind or renew lease when needed.
pub async fn notify_dhcpcd_rebind(device: &str) -> Result<()> {
    let mut cmd = Command::new("dhcpcd");
    cmd.args(["-n", device]);
    let status = crate::cmd::run_status_with_timeout(
        &mut cmd,
        std::time::Duration::from_secs(10),
        "dhcpcd -n",
    )
    .await?;
    if !status.success() {
        tracing::debug!(device, status = %status, "dhcpcd -n returned non-zero");
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crabrouter_model::{InterfaceRole, VlanConfig};

    #[test]
    fn renders_dhcpcd_conf_with_denyinterfaces_and_ia_pd() {
        let mut cfg = RouterConfig::default();
        cfg.vlans.push(VlanConfig {
            parent: "eth1".to_string(),
            id: 20,
            role: InterfaceRole::Lan,
            cidr: Some("192.168.20.1/24".to_string()),
            ipv6_ra_enabled: true,
            ipv6_subnet_id: None,
        });
        let conf = render_dhcpcd_conf(&cfg);
        assert!(conf.contains("denyinterfaces br-lan eth1 eth2 eth3"));
        assert!(conf.contains("interface eth0"));
        assert!(conf.contains("ia_pd 2/::/60 br-lan/0/64 eth1.20/1/64"));
    }
}
