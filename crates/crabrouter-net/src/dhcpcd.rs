use std::fmt::Write;
use std::fs;
use std::path::Path;

use crabrouter_model::{RouterConfig, WanProto};
use serde::{Deserialize, Serialize};
use tokio::process::Command;

use crate::Result;

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct WanLeaseEvent {
    pub source: String,
    pub wan_name: String,
    pub device: String,
    pub event: String,
    #[serde(default)]
    pub ip: Option<String>,
    #[serde(default)]
    pub gateway: Option<String>,
    #[serde(default)]
    pub dns_servers: Vec<String>,
    #[serde(default)]
    pub ifindex: Option<u32>,
}

/// Renders `/etc/dhcpcd.d/crabrouter.conf` (or `/etc/dhcpcd.conf` drop-in) controlling which
/// WAN interfaces `dhcpcd` manages and preventing it from touching LAN/bridge/static ports.
pub fn render_dhcpcd_conf(cfg: &RouterConfig) -> String {
    let mut out = String::from(
        "# Generated by crabrouterd — do not edit manually\n\
         duid\n\
         persistent\n\
         vendorclassid\n\
         option domain_name_servers, domain_name, domain_search, host_name\n\
         option classless_static_routes\n\
         option interface_mtu\n\
         nohook resolv.conf\n\n",
    );

    let mut deny: Vec<String> = Vec::new();
    for lan in &cfg.lans {
        deny.push(lan.bridge.clone());
        for port in &lan.ports {
            deny.push(port.clone());
        }
    }
    for wan in &cfg.wans {
        if wan.proto != WanProto::Dhcp {
            deny.push(wan.device.clone());
        }
    }
    if !deny.is_empty() {
        let _ = writeln!(out, "denyinterfaces {}", deny.join(" "));
    }

    for wan in &cfg.wans {
        if wan.proto != WanProto::Dhcp {
            continue;
        }
        let _ = writeln!(out, "\ninterface {}", wan.device);
        let _ = writeln!(out, "    metric {}", wan.metric);
        if wan.ipv6_pd {
            out.push_str("    ipv6rs\n    ia_na 1\n    ia_pd 2\n");
        }
    }

    out
}

/// Renders `/etc/dhcpcd.exit-hook` (sourced by `dhcpcd-run-hooks`) posting lease changes to
/// `crabrouterd`. Kept under `/etc` because `/usr` is a read-only squashfs on the appliance.
pub fn render_dhcpcd_hook_script(endpoint_url: &str) -> String {
    format!(
        "#!/bin/sh\n\
         # Generated by crabrouterd — dhcpcd hook\n\
         case \"$reason\" in\n\
           BOUND|RENEW|REBIND|REBOOT|EXPIRE|RELEASE|STOP|NOCARRIER)\n\
             PAYLOAD=$(printf '{{\"source\":\"dhcpcd\",\"wan_name\":\"%s\",\"device\":\"%s\",\"event\":\"%s\",\"ip\":\"%s\",\"gateway\":\"%s\",\"dns_servers\":[]}}' \\\n\
               \"$interface\" \"$interface\" \"$reason\" \"${{new_ip_address:-}}\" \"${{new_routers%% *}}\")\n\
             if command -v curl >/dev/null 2>&1; then\n\
               curl -fsS -X POST -H 'Content-Type: application/json' -d \"$PAYLOAD\" '{endpoint_url}' >/dev/null 2>&1 || true\n\
             fi\n\
             ;;\n\
         esac\n"
    )
}

/// Writes `dhcpcd` configuration and exit hook script atomically.
pub fn sync_dhcpcd_files(
    cfg: &RouterConfig,
    conf_path: &Path,
    hook_path: &Path,
    endpoint_url: &str,
) -> Result<()> {
    if let Some(parent) = conf_path.parent()
        && !parent.as_os_str().is_empty()
    {
        fs::create_dir_all(parent)?;
    }
    let tmp_conf = conf_path.with_extension("conf.tmp");
    fs::write(&tmp_conf, render_dhcpcd_conf(cfg))?;
    fs::rename(&tmp_conf, conf_path)?;

    if let Some(parent) = hook_path.parent()
        && !parent.as_os_str().is_empty()
    {
        fs::create_dir_all(parent)?;
    }
    fs::write(hook_path, render_dhcpcd_hook_script(endpoint_url))?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let _ = fs::set_permissions(hook_path, fs::Permissions::from_mode(0o755));
    }
    Ok(())
}

/// Triggers `dhcpcd -n <iface>` to rebind or renew lease when needed.
pub async fn notify_dhcpcd_rebind(device: &str) -> Result<()> {
    let status = Command::new("dhcpcd").args(["-n", device]).status().await?;
    if !status.success() {
        tracing::debug!(device, status = %status, "dhcpcd -n returned non-zero");
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_dhcpcd_conf_with_denyinterfaces_and_ia_pd() {
        let cfg = RouterConfig::default();
        let conf = render_dhcpcd_conf(&cfg);
        assert!(conf.contains("denyinterfaces br-lan eth1 eth2 eth3"));
        assert!(conf.contains("interface eth0"));
        assert!(conf.contains("ia_pd 2"));
    }
}
