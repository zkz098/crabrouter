use std::fmt::Write;
use std::path::Path;

use crabrouter_model::{CakeDiffserv, QdiscAlgo, QosInterfaceConfig, RouterConfig};
use tokio::process::Command;

use crate::Result;

/// Compiles `RouterConfig.qos` into a human-readable `tc` script for previewing and execution.
///
/// Supports:
/// - **`CAKE`** (`sch_cake`) with bandwidth shaping, Diffserv tins (`diffserv4`, `diffserv3`,
///   `besteffort`), NAT-aware per-host fairness (`nat dual-srchost` / `nat dual-dsthost`),
///   TCP `ack-filter`, and framing overhead compensation (`overhead <N>`).
/// - **`fq_codel`** (`sch_fq_codel` + `HTB` rate shaper when bandwidth limit > 0) with ECN.
/// - **Ingress (Download) shaping** via `ifb` (Intermediate Functional Block) redirection when
///   `download_kbps > 0`.
pub fn render_tc_qos_script(cfg: &RouterConfig) -> String {
    let mut out = String::from("# Generated by crabrouterd — tc QoS / Bufferbloat shaper\n");
    if !cfg.qos.enabled || cfg.qos.interfaces.is_empty() {
        out.push_str("# QoS is disabled; any existing root/ingress qdiscs will be cleared\n");
        for item in &cfg.qos.interfaces {
            let iface = item.interface.trim();
            if !iface.is_empty() {
                let _ = writeln!(out, "tc qdisc del dev {iface} root 2>/dev/null || true");
                let _ = writeln!(out, "tc qdisc del dev {iface} ingress 2>/dev/null || true");
            }
        }
        return out;
    }

    for rule in &cfg.qos.interfaces {
        let iface = rule.interface.trim();
        if iface.is_empty() {
            continue;
        }
        let _ = writeln!(out, "\n# Interface '{iface}' ({:?})", rule.algorithm);
        if !rule.enabled {
            let _ = writeln!(out, "tc qdisc del dev {iface} root 2>/dev/null || true");
            let _ = writeln!(out, "tc qdisc del dev {iface} ingress 2>/dev/null || true");
            continue;
        }

        render_egress_commands(&mut out, iface, rule);
        render_ingress_commands(&mut out, iface, rule);
    }

    out
}

fn render_egress_commands(out: &mut String, iface: &str, rule: &QosInterfaceConfig) {
    match rule.algorithm {
        QdiscAlgo::Cake => {
            let bw = if rule.upload_kbps > 0 {
                format!("bandwidth {}Kbit", rule.upload_kbps)
            } else {
                "unlimited".to_string()
            };
            let diffserv = diffserv_keyword(rule.diffserv);
            let nat = if rule.nat_aware {
                "nat dual-srchost"
            } else {
                "nonat"
            };
            let ack = if rule.ack_filter {
                "ack-filter"
            } else {
                "no-ack-filter"
            };
            let _ = writeln!(
                out,
                "tc qdisc replace dev {iface} root cake {bw} {diffserv} {nat} {ack} overhead {} rtt 100ms",
                rule.overhead_bytes
            );
        }
        QdiscAlgo::FqCodel => {
            if rule.upload_kbps > 0 {
                let rate = rule.upload_kbps;
                let _ = writeln!(
                    out,
                    "tc qdisc replace dev {iface} root handle 1: htb default 10\n\
                     tc class replace dev {iface} parent 1: classid 1:10 htb rate {rate}Kbit ceil {rate}Kbit\n\
                     tc qdisc replace dev {iface} parent 1:10 handle 100: fq_codel quantum 300 ecn"
                );
            } else {
                let _ = writeln!(
                    out,
                    "tc qdisc replace dev {iface} root fq_codel quantum 300 ecn"
                );
            }
        }
    }
}

fn render_ingress_commands(out: &mut String, iface: &str, rule: &QosInterfaceConfig) {
    let ifb = ifb_name_for(iface);
    if rule.download_kbps == 0 {
        let _ = writeln!(out, "tc qdisc del dev {iface} ingress 2>/dev/null || true");
        return;
    }

    let _ = writeln!(
        out,
        "ip link add name {ifb} type ifb 2>/dev/null || true\n\
         ip link set dev {ifb} up\n\
         tc qdisc replace dev {iface} handle ffff: ingress\n\
         tc filter replace dev {iface} parent ffff: protocol all u32 match u32 0 0 action mirred egress redirect dev {ifb}"
    );

    match rule.algorithm {
        QdiscAlgo::Cake => {
            let diffserv = diffserv_keyword(rule.diffserv);
            let nat = if rule.nat_aware {
                "nat dual-dsthost"
            } else {
                "nonat"
            };
            let _ = writeln!(
                out,
                "tc qdisc replace dev {ifb} root cake bandwidth {}Kbit {diffserv} {nat} overhead {} rtt 100ms ingress",
                rule.download_kbps, rule.overhead_bytes
            );
        }
        QdiscAlgo::FqCodel => {
            let rate = rule.download_kbps;
            let _ = writeln!(
                out,
                "tc qdisc replace dev {ifb} root handle 1: htb default 10\n\
                 tc class replace dev {ifb} parent 1: classid 1:10 htb rate {rate}Kbit ceil {rate}Kbit\n\
                 tc qdisc replace dev {ifb} parent 1:10 handle 100: fq_codel quantum 300 ecn"
            );
        }
    }
}

pub fn ifb_name_for(iface: &str) -> String {
    let sanitized: String = iface
        .chars()
        .filter(|c| c.is_ascii_alphanumeric() || *c == '-' || *c == '.')
        .collect();
    let max_suffix = 15usize.saturating_sub(4);
    let suffix = if sanitized.len() > max_suffix {
        &sanitized[..max_suffix]
    } else {
        &sanitized
    };
    format!("ifb-{suffix}")
}

const fn diffserv_keyword(d: CakeDiffserv) -> &'static str {
    match d {
        CakeDiffserv::Diffserv4 => "diffserv4",
        CakeDiffserv::Diffserv3 => "diffserv3",
        CakeDiffserv::BestEffort => "besteffort",
    }
}

/// Applies configured `tc` `CAKE` / `fq_codel` qdiscs to live host interfaces.
pub async fn apply_tc_qos(cfg: &RouterConfig) -> Result<()> {
    for rule in &cfg.qos.interfaces {
        let iface = rule.interface.trim();
        if iface.is_empty() || !Path::new("/sys/class/net").join(iface).exists() {
            continue;
        }
        if !cfg.qos.enabled || !rule.enabled {
            let _ = run_tc(&["qdisc", "del", "dev", iface, "root"]).await;
            let _ = run_tc(&["qdisc", "del", "dev", iface, "ingress"]).await;
            continue;
        }

        apply_egress_rule(iface, rule).await;
        apply_ingress_rule(iface, rule).await;
    }
    Ok(())
}

async fn apply_egress_rule(iface: &str, rule: &QosInterfaceConfig) {
    match rule.algorithm {
        QdiscAlgo::Cake => {
            let mut args: Vec<String> = vec![
                "qdisc".into(),
                "replace".into(),
                "dev".into(),
                iface.into(),
                "root".into(),
                "cake".into(),
            ];
            if rule.upload_kbps > 0 {
                args.push("bandwidth".into());
                args.push(format!("{}Kbit", rule.upload_kbps));
            } else {
                args.push("unlimited".into());
            }
            args.push(diffserv_keyword(rule.diffserv).into());
            if rule.nat_aware {
                args.push("nat".into());
                args.push("dual-srchost".into());
            } else {
                args.push("nonat".into());
            }
            args.push(
                if rule.ack_filter {
                    "ack-filter"
                } else {
                    "no-ack-filter"
                }
                .into(),
            );
            args.push("overhead".into());
            args.push(rule.overhead_bytes.to_string());
            args.push("rtt".into());
            args.push("100ms".into());
            let ref_args: Vec<&str> = args.iter().map(String::as_str).collect();
            if let Err(err) = run_tc(&ref_args).await {
                tracing::warn!(iface, error = %err, "failed to apply egress CAKE qdisc");
            }
        }
        QdiscAlgo::FqCodel => {
            let _ = run_tc(&["qdisc", "del", "dev", iface, "root"]).await;
            if rule.upload_kbps > 0 {
                let rate = format!("{}Kbit", rule.upload_kbps);
                let _ = run_tc(&[
                    "qdisc", "replace", "dev", iface, "root", "handle", "1:", "htb", "default",
                    "10",
                ])
                .await;
                let _ = run_tc(&[
                    "class", "replace", "dev", iface, "parent", "1:", "classid", "1:10", "htb",
                    "rate", &rate, "ceil", &rate,
                ])
                .await;
                let _ = run_tc(&[
                    "qdisc", "replace", "dev", iface, "parent", "1:10", "handle", "100:",
                    "fq_codel", "quantum", "300", "ecn",
                ])
                .await;
            } else {
                let _ = run_tc(&[
                    "qdisc", "replace", "dev", iface, "root", "fq_codel", "quantum", "300", "ecn",
                ])
                .await;
            }
        }
    }
}

async fn apply_ingress_rule(iface: &str, rule: &QosInterfaceConfig) {
    let ifb = ifb_name_for(iface);
    if rule.download_kbps == 0 {
        let _ = run_tc(&["qdisc", "del", "dev", iface, "ingress"]).await;
        return;
    }

    let mut add_ifb = Command::new("ip");
    add_ifb.args(["link", "add", "name", &ifb, "type", "ifb"]);
    let _ = crate::cmd::run_output_with_timeout(
        &mut add_ifb,
        std::time::Duration::from_secs(5),
        "ip link add ifb",
    )
    .await;
    let mut up_ifb = Command::new("ip");
    up_ifb.args(["link", "set", "dev", &ifb, "up"]);
    let _ = crate::cmd::run_output_with_timeout(
        &mut up_ifb,
        std::time::Duration::from_secs(5),
        "ip link set ifb up",
    )
    .await;

    let _ = run_tc(&[
        "qdisc", "replace", "dev", iface, "handle", "ffff:", "ingress",
    ])
    .await;
    let _ = run_tc(&[
        "filter", "replace", "dev", iface, "parent", "ffff:", "protocol", "all", "u32", "match",
        "u32", "0", "0", "action", "mirred", "egress", "redirect", "dev", &ifb,
    ])
    .await;

    match rule.algorithm {
        QdiscAlgo::Cake => {
            let bw = format!("{}Kbit", rule.download_kbps);
            let overhead = rule.overhead_bytes.to_string();
            let mut args = vec![
                "qdisc",
                "replace",
                "dev",
                &ifb,
                "root",
                "cake",
                "bandwidth",
                &bw,
                diffserv_keyword(rule.diffserv),
            ];
            if rule.nat_aware {
                args.extend_from_slice(&["nat", "dual-dsthost"]);
            } else {
                args.push("nonat");
            }
            args.extend_from_slice(&["overhead", &overhead, "rtt", "100ms", "ingress"]);
            let _ = run_tc(&args).await;
        }
        QdiscAlgo::FqCodel => {
            let rate = format!("{}Kbit", rule.download_kbps);
            let _ = run_tc(&["qdisc", "del", "dev", &ifb, "root"]).await;
            let _ = run_tc(&[
                "qdisc", "replace", "dev", &ifb, "root", "handle", "1:", "htb", "default", "10",
            ])
            .await;
            let _ = run_tc(&[
                "class", "replace", "dev", &ifb, "parent", "1:", "classid", "1:10", "htb", "rate",
                &rate, "ceil", &rate,
            ])
            .await;
            let _ = run_tc(&[
                "qdisc", "replace", "dev", &ifb, "parent", "1:10", "handle", "100:", "fq_codel",
                "quantum", "300", "ecn",
            ])
            .await;
        }
    }
}

async fn run_tc(args: &[&str]) -> std::result::Result<(), String> {
    let mut cmd = Command::new("tc");
    cmd.args(args);
    let out =
        crate::cmd::run_output_with_timeout(&mut cmd, std::time::Duration::from_secs(10), "tc")
            .await
            .map_err(|e| e.to_string())?;
    if out.status.success() {
        Ok(())
    } else {
        Err(String::from_utf8_lossy(&out.stderr).trim().to_string())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_cake_and_fq_codel_shaping_scripts() {
        let mut cfg = RouterConfig::default();
        cfg.qos.enabled = true;
        cfg.qos.interfaces.push(QosInterfaceConfig {
            interface: "eth0".to_string(),
            enabled: true,
            algorithm: QdiscAlgo::Cake,
            upload_kbps: 50_000,
            download_kbps: 500_000,
            overhead_bytes: 26,
            nat_aware: true,
            ack_filter: true,
            diffserv: CakeDiffserv::Diffserv4,
        });
        cfg.qos.interfaces.push(QosInterfaceConfig {
            interface: "br-lan".to_string(),
            enabled: true,
            algorithm: QdiscAlgo::FqCodel,
            upload_kbps: 100_000,
            download_kbps: 0,
            overhead_bytes: 18,
            nat_aware: false,
            ack_filter: false,
            diffserv: CakeDiffserv::BestEffort,
        });

        let script = render_tc_qos_script(&cfg);
        assert!(script.contains(
            "tc qdisc replace dev eth0 root cake bandwidth 50000Kbit diffserv4 nat dual-srchost ack-filter overhead 26 rtt 100ms"
        ));
        assert!(script.contains(
            "tc qdisc replace dev ifb-eth0 root cake bandwidth 500000Kbit diffserv4 nat dual-dsthost overhead 26 rtt 100ms ingress"
        ));
        assert!(script.contains(
            "tc qdisc replace dev br-lan parent 1:10 handle 100: fq_codel quantum 300 ecn"
        ));
    }
}
