const ETHTOOL_TIMEOUT: Duration = Duration::from_secs(5);

/// Computes a Linux `sysfs` `CPU` bitmask string (comma-separated 32-bit hex chunks).
///
/// When `cpu_cores >= 4` and `exclude_cpu0` is `true`, bit `0` is cleared so `CPU0` stays
/// available for hardware `IRQ` processing on single-queue interfaces.
pub fn compute_cpu_mask_hex(cpu_cores: u32, exclude_cpu0: bool) -> String {
    let cores = cpu_cores.max(1);
    let words_len = usize::try_from(cores.div_ceil(32)).unwrap_or(1);
    let mut words = vec![0u32; words_len];

    for cpu in 0..cores {
        if exclude_cpu0 && cores >= 4 && cpu == 0 {
            continue;
        }
        let word_idx = usize::try_from(cpu / 32).unwrap_or(0);
        words[word_idx] |= 1u32 << (cpu % 32);
    }

    words
        .into_iter()
        .rev()
        .map(|w| format!("{w:08x}"))
        .collect::<Vec<_>>()
        .join(",")
}

/// Computes the `CPU` bitmask selecting a single `CPU` core index for per-queue `XPS`.
pub fn compute_single_cpu_mask_hex(cpu_idx: u32) -> String {
    let word_idx = usize::try_from(cpu_idx / 32).unwrap_or(0);
    let mut words = vec![0u32; word_idx + 1];
    words[word_idx] = 1u32 << (cpu_idx % 32);
    words
        .into_iter()
        .rev()
        .map(|w| format!("{w:08x}"))
        .collect::<Vec<_>>()
        .join(",")
}

/// Renders `RouterConfig.nic_tuning` into a deterministic `ethtool` & `sysfs` script preview.
pub fn render_nic_tuning_script(cfg: &RouterConfig) -> String {
    let mut out = String::from(
        "# Generated by crabrouterd — NIC driver-level tuning (ethtool + RPS/XPS/RFS)\n",
    );
    let enabled_items: Vec<&NicTuningConfig> =
        cfg.nic_tuning.iter().filter(|i| i.enabled).collect();
    if enabled_items.is_empty() {
        out.push_str("# No active NIC tuning policies configured\n");
        return out;
    }

    let cpu_cores = std::thread::available_parallelism()
        .map_or(1, |n| u32::try_from(n.get()).unwrap_or(u32::MAX));
    let mut max_rfs = 0u32;

    for item in enabled_items {
        let iface = item.interface.trim();
        let eff = item.resolve_effective();
        let _ = writeln!(out, "\n# Interface '{iface}' (profile: {:?})", item.profile);
        render_ethtool_commands(&mut out, iface, &eff);
        render_steering_commands(&mut out, iface, &eff, cpu_cores);
        if eff.rps_mode != RpsMode::Off
            && let Some(entries) = eff.rfs_flow_entries
        {
            max_rfs = max_rfs.max(entries);
        }
    }

    if max_rfs > 0 {
        let _ = writeln!(
            out,
            "\n# Global RFS flow table entries\necho {max_rfs} > /proc/sys/net/core/rps_sock_flow_entries"
        );
    }
    out
}

fn render_ethtool_commands(out: &mut String, iface: &str, eff: &EffectiveNicTuning) {
    let offload_pairs = offload_flag_pairs(eff);
    if !offload_pairs.is_empty() {
        let args = offload_pairs
            .iter()
            .map(|(k, v)| format!("{k} {}", on_off(*v)))
            .collect::<Vec<_>>()
            .join(" ");
        let _ = writeln!(out, "ethtool -K {iface} {args}");
    }

    let mut pause_args = Vec::new();
    if let Some(rx) = eff.pause_rx {
        pause_args.push(format!("rx {}", on_off(rx)));
    }
    if let Some(tx) = eff.pause_tx {
        pause_args.push(format!("tx {}", on_off(tx)));
    }
    if !pause_args.is_empty() {
        let _ = writeln!(out, "ethtool -A {iface} {}", pause_args.join(" "));
    }

    let mut ring_args = Vec::new();
    if let Some(rx) = eff.rx_ring {
        ring_args.push(format!("rx {rx}"));
    }
    if let Some(tx) = eff.tx_ring {
        ring_args.push(format!("tx {tx}"));
    }
    if !ring_args.is_empty() {
        let _ = writeln!(out, "ethtool -G {iface} {}", ring_args.join(" "));
    }
}

fn render_steering_commands(
    out: &mut String,
    iface: &str,
    eff: &EffectiveNicTuning,
    cpu_cores: u32,
) {
    match eff.rps_mode {
        RpsMode::Off => {
            let _ = writeln!(out, "# RPS disabled on {iface}");
        }
        RpsMode::Auto => {
            let mask = compute_cpu_mask_hex(cpu_cores, true);
            let _ = writeln!(
                out,
                "for q in /sys/class/net/{iface}/queues/rx-*; do echo {mask} > \"$q/rps_cpus\"; done"
            );
        }
        RpsMode::Custom => {
            if let Some(mask) = eff.rps_mask.as_deref() {
                let _ = writeln!(
                    out,
                    "for q in /sys/class/net/{iface}/queues/rx-*; do echo {} > \"$q/rps_cpus\"; done",
                    mask.trim()
                );
            }
        }
    }
    if eff.xps_enabled {
        let _ = writeln!(
            out,
            "# XPS enabled per TX queue across {cpu_cores} CPU(s) on {iface}"
        );
    }
    if eff.rps_mode != RpsMode::Off
        && let Some(entries) = eff.rfs_flow_entries
        && entries > 0
    {
        let _ = writeln!(
            out,
            "for q in /sys/class/net/{iface}/queues/rx-*; do echo {entries} > \"$q/rps_flow_cnt\"; done"
        );
    }
}

/// Applies configured `NIC` driver-level tuning to live host interfaces incrementally.
///
/// Unsupported driver features (`EOPNOTSUPP`) and missing interfaces are logged and skipped
/// without aborting the commit, while invalid interface names return an error.
pub async fn apply_nic_tuning(cfg: &RouterConfig) -> Result<()> {
    let mut global_rfs_max = 0u32;
    for item in &cfg.nic_tuning {
        if !item.enabled {
            continue;
        }
        let eff = item.resolve_effective();
        if eff.rps_mode != RpsMode::Off
            && let Some(entries) = eff.rfs_flow_entries
        {
            global_rfs_max = global_rfs_max.max(entries);
        }
    }
    if global_rfs_max > 0 {
        write_sysfs_if_present(
            Path::new("/proc/sys/net/core/rps_sock_flow_entries"),
            &global_rfs_max.to_string(),
        );
    }

    for item in &cfg.nic_tuning {
        if !item.enabled {
            continue;
        }
        apply_single_nic(item).await?;
    }
    Ok(())
}

async fn apply_single_nic(item: &NicTuningConfig) -> Result<()> {
    let iface = validate_iface_name(&item.interface)?;
    let net_dir = Path::new("/sys/class/net").join(iface);
    if !net_dir.exists() {
        tracing::warn!(
            iface,
            "skipping NIC tuning because interface does not exist"
        );
        return Ok(());
    }

    let snap = probe_nic_capabilities(iface).await?;
    let eff = item.resolve_effective();

    if snap.ethtool_available {
        apply_ethtool_offloads(iface, &eff, &snap).await?;
        apply_ethtool_pause(iface, &eff, &snap).await?;
        apply_ethtool_rings(iface, &eff, &snap).await?;
    } else {
        tracing::warn!(
            iface,
            "ethtool binary not found; applying sysfs RPS/XPS/RFS only"
        );
    }

    apply_rps_xps_rfs(iface, &net_dir, &eff, &snap);
    Ok(())
}

async fn apply_ethtool_offloads(
    iface: &str,
    eff: &EffectiveNicTuning,
    snap: &NicCapabilitiesSnapshot,
) -> Result<()> {
    let observed = [
        ("gro", eff.gro, snap.offloads.gro),
        ("gso", eff.gso, snap.offloads.gso),
        ("tso", eff.tso, snap.offloads.tso),
        ("lro", eff.lro, snap.offloads.lro),
        ("rx", eff.rx_checksum, snap.offloads.rx_checksum),
        ("tx", eff.tx_checksum, snap.offloads.tx_checksum),
    ];

    let pending: Vec<(&str, bool)> = observed
        .into_iter()
        .filter_map(|(flag, desired_opt, cur_opt)| {
            let desired = desired_opt?;
            if should_skip_offload(desired, cur_opt) {
                return None;
            }
            Some((flag, desired))
        })
        .collect();

    if pending.is_empty() {
        return Ok(());
    }

    let mut args = vec!["-K", iface];
    for (k, v) in &pending {
        args.push(k);
        args.push(on_off(*v));
    }
    if run_ethtool_apply(&args, iface).await? {
        return Ok(());
    }

    // Fall back to per-feature invocations so one unsupported flag does not block others.
    for (k, v) in pending {
        let _ = run_ethtool_apply(&["-K", iface, k, on_off(v)], iface).await?;
    }
    Ok(())
}

fn should_skip_offload(desired: bool, current: Option<OffloadFeatureState>) -> bool {
    let Some(cur) = current else {
        return false;
    };
    cur.fixed || cur.enabled == desired
}

async fn apply_ethtool_pause(
    iface: &str,
    eff: &EffectiveNicTuning,
    snap: &NicCapabilitiesSnapshot,
) -> Result<()> {
    let mut args = Vec::new();
    if let Some(rx) = eff.pause_rx
        && snap.pause_rx != Some(rx)
    {
        args.push("rx");
        args.push(on_off(rx));
    }
    if let Some(tx) = eff.pause_tx
        && snap.pause_tx != Some(tx)
    {
        args.push("tx");
        args.push(on_off(tx));
    }
    if args.is_empty() {
        return Ok(());
    }
    let mut full = vec!["-A", iface];
    full.extend(args);
    let _ = run_ethtool_apply(&full, iface).await?;
    Ok(())
}

async fn apply_ethtool_rings(
    iface: &str,
    eff: &EffectiveNicTuning,
    snap: &NicCapabilitiesSnapshot,
) -> Result<()> {
    let target_rx = eff
        .rx_ring
        .map(|v| snap.rx_ring_max.map_or(v, |max| v.min(max)));
    let target_tx = eff
        .tx_ring
        .map(|v| snap.tx_ring_max.map_or(v, |max| v.min(max)));

    let mut pairs: Vec<(&str, String)> = Vec::new();
    if let Some(rx) = target_rx
        && snap.rx_ring_current != Some(rx)
    {
        pairs.push(("rx", rx.to_string()));
    }
    if let Some(tx) = target_tx
        && snap.tx_ring_current != Some(tx)
    {
        pairs.push(("tx", tx.to_string()));
    }
    if pairs.is_empty() {
        return Ok(());
    }

    let mut args: Vec<&str> = vec!["-G", iface];
    for (k, v) in &pairs {
        args.push(k);
        args.push(v.as_str());
    }
    let _ = run_ethtool_apply(&args, iface).await?;
    Ok(())
}

async fn run_ethtool_apply(args: &[&str], iface: &str) -> Result<bool> {
    let mut cmd = Command::new("ethtool");
    cmd.args(args);
    match run_output_with_timeout(&mut cmd, ETHTOOL_TIMEOUT, "ethtool").await {
        Ok(out) if out.status.success() => Ok(true),
        Ok(out) => {
            let stderr = String::from_utf8_lossy(&out.stderr);
            tracing::warn!(iface, args = ?args, stderr = %stderr.trim(), "ethtool apply reported warning");
            Ok(false)
        }
        Err(err) if err.kind() == ErrorKind::NotFound => Ok(false),
        Err(err) => Err(NetError::Io(err)),
    }
}

fn apply_rps_xps_rfs(
    iface: &str,
    net_dir: &Path,
    eff: &EffectiveNicTuning,
    snap: &NicCapabilitiesSnapshot,
) {
    let queues_dir = net_dir.join("queues");
    let cpu_cores = snap.cpu_cores.max(1);
    let rx_queues = snap.rx_queues.max(1);

    let rps_mask = match eff.rps_mode {
        RpsMode::Off => "0".to_string(),
        RpsMode::Auto => {
            if snap.rx_queues > 0 && snap.rx_queues < cpu_cores {
                compute_cpu_mask_hex(cpu_cores, snap.rx_queues == 1)
            } else {
                "0".to_string()
            }
        }
        RpsMode::Custom => eff
            .rps_mask
            .as_deref()
            .map_or_else(|| "0".to_string(), |m| m.trim().to_string()),
    };

    let per_queue_rfs = if eff.rps_mode == RpsMode::Off {
        0
    } else {
        eff.rfs_flow_entries.unwrap_or(0) / rx_queues
    };

    for idx in 0..snap.rx_queues {
        let q_dir = queues_dir.join(format!("rx-{idx}"));
        write_sysfs_if_present(&q_dir.join("rps_cpus"), &rps_mask);
        write_sysfs_if_present(&q_dir.join("rps_flow_cnt"), &per_queue_rfs.to_string());
    }

    for idx in 0..snap.tx_queues {
        let mask = if eff.xps_enabled {
            compute_single_cpu_mask_hex(idx % cpu_cores)
        } else {
            "0".to_string()
        };
        let q_dir = queues_dir.join(format!("tx-{idx}"));
        write_sysfs_if_present(&q_dir.join("xps_cpus"), &mask);
    }

    tracing::debug!(
        iface,
        rx_queues = snap.rx_queues,
        tx_queues = snap.tx_queues,
        rps_mask = %rps_mask,
        xps_enabled = eff.xps_enabled,
        per_queue_rfs,
        "applied RPS/XPS/RFS steering parameters"
    );
}

fn write_sysfs_if_present(path: &Path, val: &str) {
    if !path.exists() {
        return;
    }
    if let Err(err) = fs::write(path, val) {
        tracing::warn!(path = %path.display(), val, error = %err, "failed to write sysfs/procfs tuning value");
    }
}

fn offload_flag_pairs(eff: &EffectiveNicTuning) -> Vec<(&'static str, bool)> {
    let mut pairs = Vec::new();
    for (flag, val) in [
        ("gro", eff.gro),
        ("gso", eff.gso),
        ("tso", eff.tso),
        ("lro", eff.lro),
        ("rx", eff.rx_checksum),
        ("tx", eff.tx_checksum),
    ] {
        if let Some(v) = val {
            pairs.push((flag, v));
        }
    }
    pairs
}

const fn on_off(v: bool) -> &'static str {
    if v { "on" } else { "off" }
}

#[cfg(test)]
mod tests {
    use super::probe::{
        parse_ethtool_driver, parse_ethtool_offloads, parse_ethtool_pause, parse_ethtool_rings,
    };
    use super::*;
    use crabrouter_model::NicTuningProfile;

    #[test]
    fn parses_ethtool_driver_offloads_pause_and_rings() {
        let drv_sample = "\
driver: igc
version: 6.12.0-amd64
firmware-version: 2024:889
bus-info: 0000:01:00.0
";
        let (drv, ver, bus) = parse_ethtool_driver(drv_sample);
        assert_eq!(drv.as_deref(), Some("igc"));
        assert_eq!(ver.as_deref(), Some("6.12.0-amd64"));
        assert_eq!(bus.as_deref(), Some("0000:01:00.0"));

        let k_sample = "\
Features for eth0:
rx-checksumming: on
tx-checksumming: on [fixed]
tcp-segmentation-offload: on
generic-segmentation-offload: on
generic-receive-offload: on
large-receive-offload: off [fixed]
";
        let caps = parse_ethtool_offloads(k_sample);
        assert_eq!(
            caps.rx_checksum,
            Some(OffloadFeatureState {
                enabled: true,
                fixed: false
            })
        );
        assert_eq!(
            caps.tx_checksum,
            Some(OffloadFeatureState {
                enabled: true,
                fixed: true
            })
        );
        assert_eq!(
            caps.lro,
            Some(OffloadFeatureState {
                enabled: false,
                fixed: true
            })
        );

        let a_sample = "\
Pause parameters for eth0:
Autonegotiate:  on
RX:             on
TX:             off
";
        assert_eq!(
            parse_ethtool_pause(a_sample),
            (Some(true), Some(true), Some(false))
        );

        let g_sample = "\
Ring parameters for eth0:
Pre-set maximums:
RX:             4096
RX Mini:        n/a
TX:             4096
Current hardware settings:
RX:             256
TX:             256
";
        assert_eq!(
            parse_ethtool_rings(g_sample),
            (Some(256), Some(4096), Some(256), Some(4096))
        );
    }

    #[test]
    fn computes_cpu_masks_for_small_and_large_core_counts() {
        assert_eq!(compute_cpu_mask_hex(1, true), "00000001");
        assert_eq!(compute_cpu_mask_hex(2, true), "00000003");
        assert_eq!(compute_cpu_mask_hex(4, true), "0000000e");
        assert_eq!(compute_cpu_mask_hex(4, false), "0000000f");
        assert_eq!(compute_cpu_mask_hex(8, true), "000000fe");
        assert_eq!(compute_cpu_mask_hex(40, true), "000000ff,fffffffe");
        assert_eq!(compute_single_cpu_mask_hex(0), "00000001");
        assert_eq!(compute_single_cpu_mask_hex(33), "00000002,00000000");
    }

    #[test]
    fn renders_nic_tuning_script_with_presets_and_overrides() {
        let mut cfg = RouterConfig::default();
        cfg.nic_tuning.push(NicTuningConfig {
            interface: "eth0".to_string(),
            enabled: true,
            profile: NicTuningProfile::LowLatency,
            gro: Some(false),
            gso: None,
            tso: None,
            lro: None,
            rx_checksum: None,
            tx_checksum: None,
            pause_rx: None,
            pause_tx: None,
            rx_ring: Some(512),
            tx_ring: Some(512),
            rps_mode: RpsMode::Off,
            rps_mask: None,
            xps_enabled: false,
            rfs_flow_entries: None,
        });
        cfg.nic_tuning.push(NicTuningConfig {
            interface: "eth1".to_string(),
            enabled: true,
            profile: NicTuningProfile::HighThroughput,
            gro: None,
            gso: None,
            tso: None,
            lro: None,
            rx_checksum: None,
            tx_checksum: None,
            pause_rx: None,
            pause_tx: None,
            rx_ring: None,
            tx_ring: None,
            rps_mode: RpsMode::Custom,
            rps_mask: Some("0c".to_string()),
            xps_enabled: true,
            rfs_flow_entries: Some(65_536),
        });

        let script = render_nic_tuning_script(&cfg);
        assert!(script.contains("ethtool -K eth0 gro off lro off rx on tx on"));
        assert!(script.contains("ethtool -A eth0 rx off tx off"));
        assert!(script.contains("ethtool -G eth0 rx 512 tx 512"));
        assert!(script.contains("echo 0c > \"$q/rps_cpus\""));
        assert!(script.contains("echo 65536 > /proc/sys/net/core/rps_sock_flow_entries"));
    }
}
