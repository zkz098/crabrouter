use std::fmt::Write;
use std::fs;
use std::path::Path;

use crabrouter_model::InterfacePin;

use crate::Result;

/// Discovers physical Ethernet NICs from `/sys/class/net` (requiring a hardware `device` link,
/// `type == 1` (`ARPHRD_ETHER`), and a valid non-zero MAC) and returns sorted `InterfacePin` entries.
pub fn discover_physical_nic_pins(sys_class_net: &Path) -> Vec<InterfacePin> {
    let Ok(entries) = fs::read_dir(sys_class_net) else {
        return Vec::new();
    };
    let mut pins = Vec::new();
    for entry in entries.flatten() {
        let name = entry.file_name().to_string_lossy().to_string();
        if name == "lo" {
            continue;
        }
        let base = entry.path();
        if !base.join("device").exists() {
            continue;
        }
        let is_ether = fs::read_to_string(base.join("type")).is_ok_and(|s| s.trim() == "1");
        if !is_ether {
            continue;
        }
        let Some(mac) = fs::read_to_string(base.join("address"))
            .ok()
            .map(|s| s.trim().to_ascii_lowercase())
            .filter(|m| is_valid_unicast_mac(m))
        else {
            continue;
        };
        pins.push(InterfacePin { mac, name });
    }
    pins.sort_by(|a, b| a.name.cmp(&b.name));
    pins
}

fn is_valid_unicast_mac(mac: &str) -> bool {
    mac.len() == 17 && mac != "00:00:00:00:00:00" && mac != "ff:ff:ff:ff:ff:ff"
}

/// Renders individual `systemd.link` unit files for MAC-pinned interface naming.
/// Returns `(filename, content)` tuples such as `("10-crabrouter-wan0.link", ...)`.
pub fn render_systemd_link_files(pins: &[InterfacePin]) -> Vec<(String, String)> {
    pins.iter()
        .map(|pin| {
            let mac = pin.mac.to_ascii_lowercase();
            let name = pin.name.trim();
            let filename = format!("10-crabrouter-{name}.link");
            let content = format!(
                "# Generated by crabrouterd — do not edit manually\n\
                 [Match]\n\
                 MACAddress={mac}\n\
                 Type=ether\n\n\
                 [Link]\n\
                 Name={name}\n"
            );
            (filename, content)
        })
        .collect()
}

/// Renders a udev rules file (`/etc/udev/rules.d/70-crabrouter-net.rules`) pinning
/// physical NIC names by MAC address.
pub fn render_udev_net_rules(pins: &[InterfacePin]) -> String {
    let mut out = String::from("# Generated by crabrouterd — do not edit manually\n");
    for pin in pins {
        let mac = pin.mac.to_ascii_lowercase();
        let name = pin.name.trim();
        let _ = writeln!(
            out,
            "SUBSYSTEM==\"net\", ACTION==\"add\", DRIVERS==\"?*\", ATTR{{address}}==\"{mac}\", ATTR{{type}}==\"1\", NAME=\"{name}\""
        );
    }
    out
}

/// Writes `systemd.link` files and udev rules atomically, removing stale `10-crabrouter-*.link` files.
pub fn sync_interface_pin_files(
    pins: &[InterfacePin],
    systemd_network_dir: &Path,
    udev_rules_path: &Path,
) -> Result<()> {
    fs::create_dir_all(systemd_network_dir)?;
    let rendered = render_systemd_link_files(pins);
    let wanted_names: std::collections::HashSet<&str> =
        rendered.iter().map(|(f, _)| f.as_str()).collect();

    for entry in fs::read_dir(systemd_network_dir)? {
        let entry = entry?;
        let fname = entry.file_name();
        let fname_str = fname.to_string_lossy();
        if fname_str.starts_with("10-crabrouter-")
            && fname_str.ends_with(".link")
            && !wanted_names.contains(fname_str.as_ref())
        {
            fs::remove_file(entry.path())?;
        }
    }

    for (filename, content) in &rendered {
        let path = systemd_network_dir.join(filename);
        let tmp = systemd_network_dir.join(format!(".{filename}.tmp"));
        fs::write(&tmp, content)?;
        fs::rename(&tmp, &path)?;
    }

    if let Some(parent) = udev_rules_path.parent()
        && !parent.as_os_str().is_empty()
    {
        fs::create_dir_all(parent)?;
    }
    let udev_content = render_udev_net_rules(pins);
    let udev_tmp = udev_rules_path.with_extension("rules.tmp");
    fs::write(&udev_tmp, udev_content)?;
    fs::rename(&udev_tmp, udev_rules_path)?;

    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_systemd_link_and_udev_rules() {
        let pins = vec![InterfacePin {
            mac: "AA:BB:CC:DD:EE:FF".to_string(),
            name: "wan0".to_string(),
        }];
        let links = render_systemd_link_files(&pins);
        assert_eq!(links.len(), 1);
        assert_eq!(links[0].0, "10-crabrouter-wan0.link");
        assert!(links[0].1.contains("MACAddress=aa:bb:cc:dd:ee:ff"));
        assert!(links[0].1.contains("Name=wan0"));

        let udev = render_udev_net_rules(&pins);
        assert!(udev.contains("ATTR{address}==\"aa:bb:cc:dd:ee:ff\""));
        assert!(udev.contains("NAME=\"wan0\""));
    }

    #[test]
    fn discovers_only_physical_ethernet_nics_with_valid_mac() {
        let tmp = std::env::temp_dir().join(format!("crabrouter-pins-test-{}", std::process::id()));
        let eth0 = tmp.join("eth0");
        let br0 = tmp.join("br-lan");
        let lo = tmp.join("lo");
        fs::create_dir_all(eth0.join("device")).unwrap();
        fs::create_dir_all(&br0).unwrap();
        fs::create_dir_all(&lo).unwrap();

        fs::write(eth0.join("type"), "1\n").unwrap();
        fs::write(eth0.join("address"), "AA:BB:CC:DD:EE:01\n").unwrap();
        fs::write(br0.join("type"), "1\n").unwrap();
        fs::write(br0.join("address"), "AA:BB:CC:DD:EE:02\n").unwrap();
        fs::write(lo.join("type"), "772\n").unwrap();
        fs::write(lo.join("address"), "00:00:00:00:00:00\n").unwrap();

        let pins = discover_physical_nic_pins(&tmp);
        assert_eq!(pins.len(), 1);
        assert_eq!(pins[0].name, "eth0");
        assert_eq!(pins[0].mac, "aa:bb:cc:dd:ee:01");

        let _ = fs::remove_dir_all(&tmp);
    }
}
