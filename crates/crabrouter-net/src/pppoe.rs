/// Renders a `/etc/ppp/peers/crabrouter-<name>` configuration using kernel-space `rp-pppoe.so`.
pub fn render_pppd_peer(wan: &WanConfig) -> String {
    let user = wan.pppoe_username.as_deref().unwrap_or("");
    let mtu = wan.mtu.min(1492);
    let ipv6_lines = if wan.ipv6_pd {
        "+ipv6\nipv6 ,\n"
    } else {
        "+ipv6\n"
    };
    format!(
        "# Generated by crabrouterd for WAN '{}'\n\
         plugin rp-pppoe.so\n\
         nic-{}\n\
         user \"{}\"\n\
         noauth\n\
         persist\n\
         maxfail 0\n\
         holdoff 5\n\
         lcp-echo-interval 15\n\
         lcp-echo-failure 3\n\
         mtu {mtu}\n\
         mru {mtu}\n\
         defaultroute\n\
         replacedefaultroute\n\
         usepeerdns\n\
         ipparam \"{}\"\n\
         {ipv6_lines}",
        wan.name, wan.device, user, wan.name
    )
}

/// Renders `/etc/ppp/chap-secrets` or `/etc/ppp/pap-secrets` lines for configured `PPPoE` WANs.
pub fn render_ppp_secrets(wans: &[WanConfig]) -> String {
    let mut out = String::from("# Generated by crabrouterd — do not edit manually\n");
    for wan in wans {
        if wan.proto != WanProto::Pppoe {
            continue;
        }
        let Some(user) = wan.pppoe_username.as_deref() else {
            continue;
        };
        let secret = wan.pppoe_password.as_deref().unwrap_or("");
        let esc_user = escape_ppp_token(user);
        let esc_secret = escape_ppp_token(secret);
        let _ = writeln!(out, "\"{esc_user}\" * \"{esc_secret}\" *");
    }
    out
}

/// Renders `/etc/ppp/ip-up.d/90-crabrouter` (and `ip-down.d` variant) notifying `crabrouterd`
/// when a `PPPoE` link comes up or goes down.
pub fn render_pppd_hook_script(endpoint_url: &str, is_up: bool) -> String {
    let state = if is_up { "up" } else { "down" };
    format!(
        "#!/bin/sh\n\
         # Generated by crabrouterd\n\
         IFACE=\"$1\"\n\
         IPLOCAL=\"$4\"\n\
         IPREMOTE=\"$5\"\n\
         WAN_NAME=\"${{6:-$IFACE}}\"\n\
         PAYLOAD=$(printf '{{\"source\":\"pppd\",\"wan_name\":\"%s\",\"device\":\"%s\",\"event\":\"{state}\",\"ip\":\"%s\",\"gateway\":\"%s\",\"dns_servers\":[]}}' \\\n\
           \"$WAN_NAME\" \"$IFACE\" \"$IPLOCAL\" \"$IPREMOTE\")\n\
         if command -v curl >/dev/null 2>&1; then\n\
           curl -fsS -X POST -H 'Content-Type: application/json' -d \"$PAYLOAD\" '{endpoint_url}' >/dev/null 2>&1 || true\n\
         fi\n"
    )
}

/// Renders `/etc/ppp/ipv6-up.d/90-crabrouter` (and `ipv6-down.d` variant) triggering `dhcpcd`
/// `IA_PD` prefix delegation over the `ppp*` interface when `IPV6CP` completes.
pub fn render_pppd_ipv6_hook_script(endpoint_url: &str, is_up: bool) -> String {
    let state = if is_up { "ipv6_up" } else { "ipv6_down" };
    let dhcpcd_trigger = if is_up {
        "if command -v dhcpcd >/dev/null 2>&1; then\n  dhcpcd -6 -n \"$IFACE\" >/dev/null 2>&1 || true\nfi\n"
    } else {
        "if command -v dhcpcd >/dev/null 2>&1; then\n  dhcpcd -6 -k \"$IFACE\" >/dev/null 2>&1 || true\nfi\n"
    };
    format!(
        "#!/bin/sh\n\
         # Generated by crabrouterd — PPPoE IPV6CP + DHCPv6-PD hook\n\
         IFACE=\"$1\"\n\
         LLLOCAL=\"$4\"\n\
         WAN_NAME=\"${{6:-$IFACE}}\"\n\
         {dhcpcd_trigger}\
         PAYLOAD=$(printf '{{\"source\":\"pppd\",\"wan_name\":\"%s\",\"device\":\"%s\",\"event\":\"{state}\",\"ipv6_addr\":\"%s\",\"dns_servers\":[]}}' \\\n\
           \"$WAN_NAME\" \"$IFACE\" \"$LLLOCAL\")\n\
         if command -v curl >/dev/null 2>&1; then\n\
           curl -fsS -X POST -H 'Content-Type: application/json' -d \"$PAYLOAD\" '{endpoint_url}' >/dev/null 2>&1 || true\n\
         fi\n"
    )
}

fn escape_ppp_token(raw: &str) -> String {
    raw.replace('\\', "\\\\").replace('"', "\\\"")
}

/// Writes `PPPoE` peer configs, secrets (`0600`), and ip-up/down + ipv6-up/down hook scripts to disk.
pub fn sync_pppd_files(
    cfg: &RouterConfig,
    ppp_dir: &Path,
    hook_endpoint: &str,
) -> Result<Vec<String>> {
    let peers_dir = ppp_dir.join("peers");
    let up_dir = ppp_dir.join("ip-up.d");
    let down_dir = ppp_dir.join("ip-down.d");
    let v6_up_dir = ppp_dir.join("ipv6-up.d");
    let v6_down_dir = ppp_dir.join("ipv6-down.d");
    fs::create_dir_all(&peers_dir)?;
    fs::create_dir_all(&up_dir)?;
    fs::create_dir_all(&down_dir)?;
    fs::create_dir_all(&v6_up_dir)?;
    fs::create_dir_all(&v6_down_dir)?;

    let pppoe_wans: Vec<&WanConfig> = cfg
        .wans
        .iter()
        .filter(|w| w.proto == WanProto::Pppoe)
        .collect();
    let wanted_peers: std::collections::HashSet<String> = pppoe_wans
        .iter()
        .map(|w| format!("crabrouter-{}", w.name))
        .collect();

    for entry in fs::read_dir(&peers_dir)? {
        let entry = entry?;
        let name = entry.file_name().to_string_lossy().to_string();
        if name.starts_with("crabrouter-") && !wanted_peers.contains(&name) {
            fs::remove_file(entry.path())?;
        }
    }

    let mut peer_names = Vec::new();
    for wan in &pppoe_wans {
        let peer_name = format!("crabrouter-{}", wan.name);
        fs::write(peers_dir.join(&peer_name), render_pppd_peer(wan))?;
        peer_names.push(peer_name);
    }

    let secrets = render_ppp_secrets(&cfg.wans);
    for fname in ["chap-secrets", "pap-secrets"] {
        let path = ppp_dir.join(fname);
        fs::write(&path, &secrets)?;
        set_restrictive_perms(&path);
    }

    let up_hook = up_dir.join("90-crabrouter");
    fs::write(&up_hook, render_pppd_hook_script(hook_endpoint, true))?;
    set_executable_perms(&up_hook);

    let down_hook = down_dir.join("90-crabrouter");
    fs::write(&down_hook, render_pppd_hook_script(hook_endpoint, false))?;
    set_executable_perms(&down_hook);

    let v6_up_hook = v6_up_dir.join("90-crabrouter");
    fs::write(
        &v6_up_hook,
        render_pppd_ipv6_hook_script(hook_endpoint, true),
    )?;
    set_executable_perms(&v6_up_hook);

    let v6_down_hook = v6_down_dir.join("90-crabrouter");
    fs::write(
        &v6_down_hook,
        render_pppd_ipv6_hook_script(hook_endpoint, false),
    )?;
    set_executable_perms(&v6_down_hook);

    Ok(peer_names)
}

#[cfg(unix)]
fn set_restrictive_perms(path: &Path) {
    use std::os::unix::fs::PermissionsExt;
    let _ = fs::set_permissions(path, fs::Permissions::from_mode(0o600));
}

#[cfg(not(unix))]
fn set_restrictive_perms(_path: &Path) {}

#[cfg(unix)]
fn set_executable_perms(path: &Path) {
    use std::os::unix::fs::PermissionsExt;
    let _ = fs::set_permissions(path, fs::Permissions::from_mode(0o755));
}

#[cfg(not(unix))]
fn set_executable_perms(_path: &Path) {}

/// Manages supervised `pppd` child processes for active `PPPoE` WAN links.
pub struct PppdManager {
    ppp_dir: PathBuf,
    hook_endpoint: String,
    sessions: Mutex<HashMap<String, PppdSession>>,
}

struct PppdSession {
    spec_hash: String,
    task: JoinHandle<()>,
}

impl PppdManager {
    pub fn new(ppp_dir: impl Into<PathBuf>, hook_endpoint: impl Into<String>) -> Self {
        Self {
            ppp_dir: ppp_dir.into(),
            hook_endpoint: hook_endpoint.into(),
            sessions: Mutex::new(HashMap::new()),
        }
    }

    /// Reconciles running `pppd` sessions with `cfg.wans`.
    pub async fn sync(&self, cfg: &RouterConfig) -> Result<()> {
        sync_pppd_files(cfg, &self.ppp_dir, &self.hook_endpoint)?;

        let desired: HashMap<String, String> = cfg
            .wans
            .iter()
            .filter(|w| w.proto == WanProto::Pppoe)
            .map(|w| {
                let peer = render_pppd_peer(w);
                let pwd = w.pppoe_password.as_deref().unwrap_or("");
                (w.name.clone(), format!("{peer}::{pwd}"))
            })
            .collect();

        let mut guard = self.sessions.lock().await;
        let existing_keys: Vec<String> = guard.keys().cloned().collect();
        for key in existing_keys {
            let needs_stop = match desired.get(&key) {
                Some(hash) => guard.get(&key).is_some_and(|s| &s.spec_hash != hash),
                None => true,
            };
            if needs_stop && let Some(session) = guard.remove(&key) {
                session.task.abort();
                tracing::info!(wan = %key, "stopped pppd session");
            }
        }

        for (wan_name, spec_hash) in desired {
            if guard.contains_key(&wan_name) {
                continue;
            }
            let peer_name = format!("crabrouter-{wan_name}");
            let wan_label = wan_name.clone();
            let task = tokio::spawn(async move {
                supervise_pppd_loop(&wan_label, &peer_name).await;
            });
            guard.insert(wan_name, PppdSession { spec_hash, task });
        }

        Ok(())
    }
}

async fn supervise_pppd_loop(wan_name: &str, peer_name: &str) {
    let mut backoff = Duration::from_secs(2);
    loop {
        tracing::info!(wan = %wan_name, peer = %peer_name, "starting pppd");
        match spawn_pppd_child(peer_name) {
            Ok(mut child) => match child.wait().await {
                Ok(status) => {
                    tracing::warn!(wan = %wan_name, status = %status, "pppd exited; restarting");
                }
                Err(err) => {
                    tracing::error!(wan = %wan_name, error = %err, "pppd wait error");
                }
            },
            Err(err) => {
                tracing::error!(wan = %wan_name, error = %err, "failed to spawn pppd");
            }
        }
        tokio::time::sleep(backoff).await;
        backoff = (backoff * 2).min(Duration::from_secs(60));
    }
}

fn spawn_pppd_child(peer_name: &str) -> std::io::Result<Child> {
    Command::new("pppd")
        .args(["call", peer_name, "nodetach"])
        .kill_on_drop(true)
        .spawn()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_peer_and_secrets() {
        let wan = WanConfig {
            name: "wan0".to_string(),
            device: "eth0".to_string(),
            proto: WanProto::Pppoe,
            static_cidr: None,
            gateway: None,
            pppoe_username: Some("user@isp".to_string()),
            pppoe_password: Some("s3cr\"et".to_string()),
            mtu: 1500,
            ipv6_pd: true,
            ipv6_pd_prefix_len: 60,
            metric: 100,
            weight: 1,
            table_id: None,
            health_check_enabled: true,
            probe_targets: Vec::new(),
        };
        let peer = render_pppd_peer(&wan);
        assert!(peer.contains("plugin rp-pppoe.so"));
        assert!(peer.contains("nic-eth0"));
        assert!(peer.contains("mtu 1492"));
        assert!(peer.contains("ipv6 ,"));

        let secrets = render_ppp_secrets(&[wan]);
        assert!(secrets.contains("\"user@isp\" * \"s3cr\\\"et\" *"));
    }
}
