use std::collections::{HashMap, HashSet};
use std::fmt::Write;
use std::fs;
use std::net::Ipv4Addr;
use std::path::Path;

use crabrouter_model::{DhcpLeaseEntry, InterfaceRole, Ipv6LanMode, RouterConfig};
use ipnet::IpNet;

use crate::{Result, ServiceError};

/// Renders `dnsmasq.conf` for the secondary local-authority role:
/// - Listens on `127.0.0.1:<dnsmasq_dns_port>` (default 5354) for `.lan` & private PTR lookups
/// - Disables local DNS caching (`cache-size=0`), leaving caching/DoT/DoH/filtering to `crabdns`
/// - Serves `DHCPv4` (and DHCP option 6 pointing clients to `crabdns:53`), including static `dhcp-host` bindings
/// - Serves `IPv6 RA` + stateless `DHCPv6` / `SLAAC` (`/64` `constructor:<iface>`) across LAN bridges and LAN VLANs
pub fn render_dnsmasq_conf(cfg: &RouterConfig) -> Result<String> {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "# Generated by crabrouterd — do not edit manually\n\
         port={}\n\
         listen-address=127.0.0.1\n\
         bind-interfaces\n\
         cache-size=0\n\
         no-resolv\n\
         domain-needed\n\
         bogus-priv\n\
         expand-hosts\n\
         dhcp-authoritative\n\
         dhcp-leasefile=/var/lib/misc/dnsmasq.leases\n\
         leasefile-ro=false\n",
        cfg.dns.dnsmasq_dns_port
    );

    let any_ra_enabled = cfg
        .lans
        .iter()
        .any(|l| l.ipv6_ra_enabled && l.ipv6_mode == Ipv6LanMode::Server)
        || cfg
            .vlans
            .iter()
            .any(|v| v.role == InterfaceRole::Lan && v.ipv6_ra_enabled);
    if any_ra_enabled {
        let _ = writeln!(
            out,
            "# IPv6 Router Advertisement & /64 Prefix Delegation (SLAAC + RDNSS)\n\
             enable-ra\n\
             ra-param=*,high,60,1800\n"
        );
    }

    for lan in &cfg.lans {
        write_lan_section(&mut out, lan)?;
    }

    if !cfg.dns.custom_hosts.is_empty() {
        out.push_str("# Custom static DNS host records\n");
        for entry in &cfg.dns.custom_hosts {
            let _ = writeln!(
                out,
                "host-record={},{}",
                entry.hostname.trim(),
                entry.ip.trim()
            );
        }
        out.push('\n');
    }

    write_vlan_ipv6_ra(&mut out, cfg);

    Ok(out)
}

fn write_lan_section(out: &mut String, lan: &crabrouter_model::LanConfig) -> Result<()> {
    let net: IpNet = lan
        .cidr
        .parse()
        .map_err(|e| ServiceError::Render(format!("invalid LAN cidr '{}': {e}", lan.cidr)))?;
    let IpNet::V4(v4_net) = net else {
        return Ok(());
    };

    let _ = writeln!(out, "# LAN '{}' ({})", lan.name, lan.bridge);
    let _ = writeln!(out, "local=/{}/", lan.domain);
    let _ = writeln!(out, "domain={}", lan.domain);

    let mut iface_emitted = false;
    if lan.dhcp_enabled {
        let base = u32::from(v4_net.network());
        let broadcast = u32::from(v4_net.broadcast());
        let start_u32 = base.saturating_add(lan.dhcp_start_offset);
        let end_u32 = start_u32
            .saturating_add(lan.dhcp_limit.saturating_sub(1))
            .min(broadcast.saturating_sub(1));

        if start_u32 <= end_u32 {
            let start_ip = Ipv4Addr::from(start_u32);
            let end_ip = Ipv4Addr::from(end_u32);
            let router_ip = v4_net.addr();
            iface_emitted = true;
            let _ = writeln!(
                out,
                "interface={}\n\
                 dhcp-range=set:{},{start_ip},{end_ip},{},{}s\n\
                 dhcp-option=tag:{},option:router,{router_ip}\n\
                 dhcp-option=tag:{},option:dns-server,{router_ip}",
                lan.bridge,
                lan.name,
                v4_net.netmask(),
                lan.dhcp_lease_secs,
                lan.name,
                lan.name,
            );
            for opt in &lan.custom_options {
                let _ = writeln!(
                    out,
                    "dhcp-option=tag:{},{},{}",
                    lan.name,
                    opt.option.trim(),
                    opt.value.trim()
                );
            }
        }

        for lease in &lan.static_leases {
            let host = lease
                .hostname
                .as_deref()
                .map(str::trim)
                .filter(|s| !s.is_empty());
            if let Some(h) = host {
                let _ = writeln!(out, "dhcp-host={},{},{}", lease.mac, lease.ip, h);
            } else {
                let _ = writeln!(out, "dhcp-host={},{}", lease.mac, lease.ip);
            }
        }
    }

    match lan.ipv6_mode {
        Ipv6LanMode::Server if lan.ipv6_ra_enabled => {
            write_lan_ipv6_ra(
                out,
                &lan.name,
                &lan.bridge,
                lan.dhcp_lease_secs,
                iface_emitted,
            );
        }
        Ipv6LanMode::Relay => {
            let _ = writeln!(
                out,
                "# IPv6 Relay mode active on '{}' — NDP/RA handled by ndppd",
                lan.bridge
            );
        }
        Ipv6LanMode::Server | Ipv6LanMode::Disabled => {}
    }
    out.push('\n');
    Ok(())
}

fn write_lan_ipv6_ra(
    out: &mut String,
    lan_name: &str,
    bridge: &str,
    lease_secs: u32,
    iface_emitted: bool,
) {
    if !iface_emitted {
        let _ = writeln!(out, "interface={bridge}");
    }
    let v6_tag = format!("{lan_name}-v6");
    let _ = writeln!(
        out,
        "dhcp-range=set:{v6_tag},::1,::ffff:ffff:ffff:ffff,constructor:{bridge},ra-names,slaac,64,{}s\n\
         dhcp-option=tag:{v6_tag},option6:dns-server,[fe80::]",
        lease_secs.max(3600)
    );
}

fn write_vlan_ipv6_ra(out: &mut String, cfg: &RouterConfig) {
    for vlan in &cfg.vlans {
        if vlan.role != InterfaceRole::Lan || !vlan.ipv6_ra_enabled {
            continue;
        }
        let ifname = format!("{}.{}", vlan.parent, vlan.id);
        let v6_tag = format!("vlan{}-v6", vlan.id);
        let _ = writeln!(
            out,
            "# VLAN '{ifname}' IPv6-PD /64 RA\n\
             interface={ifname}\n\
             dhcp-range=set:{v6_tag},::1,::ffff:ffff:ffff:ffff,constructor:{ifname},ra-names,slaac,64,43200s\n\
             dhcp-option=tag:{v6_tag},option6:dns-server,[fe80::]\n"
        );
    }
}

/// Reads active DHCP leases from `dnsmasq.leases` merged with `/proc/net/arp` neighbours
/// and marks static bindings from `RouterConfig`.
pub fn read_online_clients(
    lease_path: &Path,
    arp_path: &Path,
    cfg: &RouterConfig,
) -> Vec<DhcpLeaseEntry> {
    let static_macs: HashSet<String> = cfg
        .lans
        .iter()
        .flat_map(|l| l.static_leases.iter())
        .map(|s| s.mac.to_ascii_lowercase())
        .collect();

    let static_host_by_mac: HashMap<String, String> = cfg
        .lans
        .iter()
        .flat_map(|l| l.static_leases.iter())
        .filter_map(|s| {
            s.hostname
                .as_deref()
                .filter(|h| !h.is_empty())
                .map(|h| (s.mac.to_ascii_lowercase(), h.to_string()))
        })
        .collect();

    let mut by_mac: HashMap<String, DhcpLeaseEntry> = HashMap::new();

    if let Ok(raw) = fs::read_to_string(lease_path) {
        for line in raw.lines() {
            let cols: Vec<&str> = line.split_whitespace().collect();
            if cols.len() < 4 {
                continue;
            }
            let expires_at = cols[0].parse::<u64>().unwrap_or(0);
            let mac = cols[1].to_ascii_lowercase();
            let ip = cols[2].to_string();
            let hostname = if cols[3] == "*" {
                static_host_by_mac
                    .get(&mac)
                    .cloned()
                    .unwrap_or_else(|| "-".to_string())
            } else {
                cols[3].to_string()
            };
            let client_id = cols
                .get(4)
                .filter(|&&c| c != "*")
                .map(std::string::ToString::to_string);
            let is_static = static_macs.contains(&mac);
            by_mac.insert(
                mac.clone(),
                DhcpLeaseEntry {
                    expires_at,
                    mac,
                    ip,
                    hostname,
                    client_id,
                    is_static,
                },
            );
        }
    }

    let lan_bridges: HashSet<&str> = cfg.lans.iter().map(|l| l.bridge.as_str()).collect();
    if let Ok(raw_arp) = fs::read_to_string(arp_path) {
        for line in raw_arp.lines().skip(1) {
            let cols: Vec<&str> = line.split_whitespace().collect();
            if cols.len() < 6 {
                continue;
            }
            let ip = cols[0];
            let flags = cols[2];
            let mac = cols[3].to_ascii_lowercase();
            let dev = cols[5];
            if flags == "0x0" || mac == "00:00:00:00:00:00" || !lan_bridges.contains(dev) {
                continue;
            }
            by_mac.entry(mac.clone()).or_insert_with(|| DhcpLeaseEntry {
                expires_at: 0,
                mac: mac.clone(),
                ip: ip.to_string(),
                hostname: static_host_by_mac
                    .get(&mac)
                    .cloned()
                    .unwrap_or_else(|| "-".to_string()),
                client_id: None,
                is_static: static_macs.contains(&mac),
            });
        }
    }

    let mut entries: Vec<DhcpLeaseEntry> = by_mac.into_values().collect();
    entries.sort_by(|a, b| a.ip.cmp(&b.ip));
    entries
}

#[cfg(test)]
mod tests {
    use super::*;
    use crabrouter_model::{DhcpStaticLease, VlanConfig};

    #[test]
    fn renders_dnsmasq_on_5354_with_zero_cache_and_static_leases() {
        let mut cfg = RouterConfig::default();
        cfg.lans[0].static_leases.push(DhcpStaticLease {
            name: "nas".to_string(),
            mac: "aa:bb:cc:11:22:33".to_string(),
            ip: "192.168.10.50".to_string(),
            hostname: Some("nas".to_string()),
        });
        cfg.vlans.push(VlanConfig {
            parent: "eth1".to_string(),
            id: 20,
            role: InterfaceRole::Lan,
            cidr: Some("192.168.20.1/24".to_string()),
            ipv6_ra_enabled: true,
            ipv6_subnet_id: Some(1),
        });
        let conf = render_dnsmasq_conf(&cfg).unwrap();
        assert!(conf.contains("port=5354"));
        assert!(conf.contains("cache-size=0"));
        assert!(conf.contains("local=/lan/"));
        assert!(conf.contains("enable-ra"));
        assert!(
            conf.contains("dhcp-range=set:lan,192.168.10.100,192.168.10.249,255.255.255.0,43200s")
        );
        assert!(conf.contains(
            "dhcp-range=set:lan-v6,::1,::ffff:ffff:ffff:ffff,constructor:br-lan,ra-names,slaac,64,43200s"
        ));
        assert!(conf.contains(
            "dhcp-range=set:vlan20-v6,::1,::ffff:ffff:ffff:ffff,constructor:eth1.20,ra-names,slaac,64,43200s"
        ));
        assert!(conf.contains("dhcp-host=aa:bb:cc:11:22:33,192.168.10.50,nas"));
    }

    #[test]
    fn renders_custom_dhcp_options_and_custom_hosts() {
        use crabrouter_model::{CustomHostEntry, DhcpCustomOption};

        let mut cfg = RouterConfig::default();
        cfg.lans[0].custom_options.push(DhcpCustomOption {
            option: "42".to_string(),
            value: "192.168.10.1".to_string(),
        });
        cfg.dns.custom_hosts.push(CustomHostEntry {
            hostname: "pve.home".to_string(),
            ip: "192.168.10.10".to_string(),
        });
        let conf = render_dnsmasq_conf(&cfg).unwrap();
        assert!(conf.contains("dhcp-option=tag:lan,42,192.168.10.1"));
        assert!(conf.contains("host-record=pve.home,192.168.10.10"));
    }
}
