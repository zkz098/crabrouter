/// Renders `crowdsec-firewall-bouncer.yaml` targeting `crabrouter` nftables sets.
pub fn render_crowdsec_bouncer_conf(cfg: &RouterConfig) -> String {
    if !cfg.crowdsec.enabled || !cfg.crowdsec.bouncer_enabled {
        return "# CrowdSec bouncer is disabled\n".to_string();
    }
    let freq = format!("{}s", cfg.crowdsec.update_frequency_secs.max(5));
    let mut out = String::from("# Generated by crabrouterd — do not edit manually\n");
    let _ = writeln!(out, "mode: nftables");
    let _ = writeln!(out, "update_frequency: {freq}");
    let _ = writeln!(out, "api_url: http://{}/", cfg.crowdsec.lapi_listen.trim());
    let _ = writeln!(out, "log_mode: stdout");
    let _ = writeln!(out, "log_level: info");
    out.push_str(
        "nftables:\n\
         \x20 ipv4:\n\
         \x20   enabled: true\n\
         \x20   set-only: true\n\
         \x20   table: crabrouter\n\
         \x20   chain: input\n\
         \x20   set-name: crowdsec_block_v4\n\
         \x20 ipv6:\n\
         \x20   enabled: true\n\
         \x20   set-only: true\n\
         \x20   table: crabrouter\n\
         \x20   chain: input\n\
         \x20   set-name: crowdsec_block_v6\n",
    );
    out
}

/// Renders `/run/crabrouter/crowdsec-acquis.yaml` for journald log ingestion.
pub fn render_crowdsec_acquis_yaml(cfg: &RouterConfig) -> String {
    if !cfg.crowdsec.enabled {
        return "# CrowdSec is disabled\n".to_string();
    }
    String::from(
        "# Generated by crabrouterd — do not edit manually\n\
         source: journalctl\n\
         journalctl_filter:\n\
         \x20 - _SYSTEMD_UNIT=ssh.service\n\
         labels:\n\
         \x20 type: syslog\n\
         ---\n\
         source: journalctl\n\
         journalctl_filter:\n\
         \x20 - _SYSTEMD_UNIT=crabrouterd.service\n\
         labels:\n\
         \x20 type: crabrouter\n",
    )
}

#[derive(Debug, Deserialize)]
struct CscliAlertItem {
    #[serde(default)]
    decisions: Vec<CscliDecisionRaw>,
}

#[derive(Debug, Deserialize)]
struct CscliDecisionRaw {
    #[serde(default)]
    id: i64,
    #[serde(default)]
    origin: String,
    #[serde(rename = "type", default)]
    decision_type: String,
    #[serde(default)]
    scope: String,
    #[serde(default)]
    value: String,
    #[serde(default)]
    duration: String,
    #[serde(default)]
    scenario: String,
}

/// Runtime manager for `CrowdSec` decision inspection and XDP blocklist synchronization.
#[derive(Clone)]
pub struct CrowdSecManager {
    status: Arc<RwLock<CrowdSecStatus>>,
    dry_run: bool,
}

impl CrowdSecManager {
    pub fn new(dry_run: bool) -> Self {
        Self {
            status: Arc::new(RwLock::new(CrowdSecStatus {
                enabled: false,
                bouncer_enabled: false,
                agent_running: false,
                bouncer_running: false,
                active_decisions: 0,
                decisions: Vec::new(),
                last_synced_at: None,
                last_error: None,
            })),
            dry_run,
        }
    }

    pub async fn status(&self) -> CrowdSecStatus {
        self.status.read().await.clone()
    }

    /// Queries `cscli decisions list -o json` (or returns dry-run state) and updates cached status.
    pub async fn refresh_decisions(&self, cfg: &RouterConfig) -> CrowdSecStatus {
        let mut next = CrowdSecStatus {
            enabled: cfg.crowdsec.enabled,
            bouncer_enabled: cfg.crowdsec.bouncer_enabled,
            agent_running: false,
            bouncer_running: false,
            active_decisions: 0,
            decisions: Vec::new(),
            last_synced_at: Some(Utc::now().to_rfc3339()),
            last_error: None,
        };

        if !cfg.crowdsec.enabled {
            *self.status.write().await = next.clone();
            return next;
        }

        if self.dry_run {
            next.agent_running = true;
            next.bouncer_running = cfg.crowdsec.bouncer_enabled;
            *self.status.write().await = next.clone();
            return next;
        }

        match fetch_cscli_decisions().await {
            Ok(decisions) => {
                next.agent_running = true;
                next.bouncer_running = cfg.crowdsec.bouncer_enabled;
                next.active_decisions = decisions.len();
                next.decisions = decisions;
            }
            Err(err) => {
                next.last_error = Some(err);
            }
        }

        *self.status.write().await = next.clone();
        next
    }
}

async fn fetch_cscli_decisions() -> std::result::Result<Vec<CrowdSecDecision>, String> {
    let output = Command::new("cscli")
        .args(["decisions", "list", "-o", "json"])
        .output()
        .await
        .map_err(|e| format!("failed to run cscli: {e}"))?;
    if !output.status.success() {
        let stderr = String::from_utf8_lossy(&output.stderr).trim().to_string();
        return Err(format!("cscli decisions list failed: {stderr}"));
    }
    let stdout = String::from_utf8_lossy(&output.stdout);
    parse_cscli_decisions_json(&stdout)
}

pub fn parse_cscli_decisions_json(raw: &str) -> std::result::Result<Vec<CrowdSecDecision>, String> {
    let trimmed = raw.trim();
    if trimmed.is_empty() || trimmed == "null" {
        return Ok(Vec::new());
    }
    let alerts: Vec<CscliAlertItem> =
        serde_json::from_str(trimmed).map_err(|e| format!("invalid cscli JSON: {e}"))?;
    let mut out = Vec::new();
    for alert in alerts {
        for d in alert.decisions {
            out.push(CrowdSecDecision {
                id: d.id,
                origin: d.origin,
                decision_type: d.decision_type,
                scope: d.scope,
                value: d.value,
                duration: d.duration,
                scenario: d.scenario,
            });
        }
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::{parse_cscli_decisions_json, render_crowdsec_bouncer_conf};
    use crabrouter_model::RouterConfig;

    #[test]
    fn renders_bouncer_nftables_set_only_config() {
        let mut cfg = RouterConfig::default();
        cfg.crowdsec.enabled = true;
        let conf = render_crowdsec_bouncer_conf(&cfg);
        assert!(conf.contains("set-only: true"));
        assert!(conf.contains("set-name: crowdsec_block_v4"));
        assert!(conf.contains("set-name: crowdsec_block_v6"));
    }

    #[test]
    fn parses_cscli_decisions_json() {
        let raw = r#"[{"decisions":[{"id":42,"origin":"crowdsec","type":"ban","scope":"Ip","value":"198.51.100.7","duration":"3h59m","scenario":"crowdsecurity/ssh-bf"}]}]"#;
        let parsed = parse_cscli_decisions_json(raw).expect("valid json");
        assert_eq!(parsed.len(), 1);
        assert_eq!(parsed[0].value, "198.51.100.7");
    }
}
