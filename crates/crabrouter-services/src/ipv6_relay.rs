use std::collections::BTreeMap;
use std::fmt::Write;

use crabrouter_model::{Ipv6LanMode, RouterConfig, WanProto};

/// Returns `true` if any LAN interface is configured for IPv6 Relay (NDP Proxy) mode.
pub fn has_ipv6_relay_enabled(cfg: &RouterConfig) -> bool {
    cfg.lans.iter().any(|l| l.ipv6_mode == Ipv6LanMode::Relay)
}

/// Renders `ndppd.conf` for IPv6 Relay (NDP Proxy) mode across upstream WAN and downstream LAN bridges.
///
/// When an ISP only delegates a single `/64` (no DHCPv6-PD), `ndppd` proxies Neighbor Solicitation /
/// Neighbor Advertisement packets between the upstream WAN and downstream LAN bridges so LAN hosts
/// can share the upstream `/64` prefix seamlessly.
pub fn render_ndppd_conf(cfg: &RouterConfig) -> String {
    if !has_ipv6_relay_enabled(cfg) {
        return "# IPv6 Relay (NDP Proxy) is disabled\n".to_string();
    }

    // Group relay LAN bridges by resolved upstream WAN device.
    let mut by_wan: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for lan in &cfg.lans {
        if lan.ipv6_mode != Ipv6LanMode::Relay {
            continue;
        }
        let wan_dev = resolve_relay_wan_device(cfg, lan.ipv6_relay_wan.as_deref());
        by_wan.entry(wan_dev).or_default().push(lan.bridge.clone());
    }

    let mut out = String::from(
        "# Generated by crabrouterd — do not edit manually\n\
         route-ttl 30000\n\n",
    );

    for (wan_dev, lan_bridges) in &by_wan {
        let _ = writeln!(out, "proxy {wan_dev} {{");
        out.push_str("    router yes\n    timeout 500\n    ttl 30000\n");
        for bridge in lan_bridges {
            let _ = writeln!(out, "    rule ::/0 {{\n        iface {bridge}\n    }}");
        }
        out.push_str("}\n\n");

        for bridge in lan_bridges {
            let _ = writeln!(
                out,
                "proxy {bridge} {{\n    router no\n    timeout 500\n    ttl 30000\n    rule ::/0 {{\n        iface {wan_dev}\n    }}\n}}\n"
            );
        }
    }

    out
}

fn resolve_relay_wan_device(cfg: &RouterConfig, wan_name: Option<&str>) -> String {
    let wan = wan_name
        .map(str::trim)
        .filter(|s| !s.is_empty())
        .and_then(|name| cfg.wans.iter().find(|w| w.name == name))
        .or_else(|| cfg.wans.first());

    match wan {
        Some(w) if w.proto == WanProto::Pppoe => "ppp0".to_string(),
        Some(w) => w.device.clone(),
        None => "eth0".to_string(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_ndppd_conf_for_relay_lan() {
        let mut cfg = RouterConfig::default();
        assert!(!has_ipv6_relay_enabled(&cfg));
        cfg.lans[0].ipv6_mode = Ipv6LanMode::Relay;
        assert!(has_ipv6_relay_enabled(&cfg));

        let conf = render_ndppd_conf(&cfg);
        assert!(conf.contains("proxy eth0 {"));
        assert!(conf.contains("iface br-lan"));
        assert!(conf.contains("proxy br-lan {"));
        assert!(conf.contains("iface eth0"));
    }
}
