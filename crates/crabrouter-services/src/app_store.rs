use crabrouter_model::{
    APP_CONTAINER_PREFIX, AppInstallRequest, ContainerActionResult, ContainerConfig, InstalledApp,
    app_container_name, build_app_container_request, builtin_app_catalog,
};

use crate::containers::{ContainerAction, ContainerBackend};
use crate::{Result, ServiceError};

/// Lists all installed App Store containers by matching `crabrouter-app-*` container names.
///
/// Returns an empty list when the container runtime is disabled or its socket is
/// temporarily unreachable so that the Extensions page can still render cleanly.
pub async fn list_installed_apps(
    backend: &dyn ContainerBackend,
    cfg: &ContainerConfig,
) -> Result<Vec<InstalledApp>> {
    if !cfg.enabled {
        return Ok(Vec::new());
    }
    let containers = match backend.list_containers(cfg, true).await {
        Ok(list) => list,
        Err(err) => {
            tracing::warn!(
                error = %err,
                "container backend unavailable while listing installed apps; returning empty list"
            );
            return Ok(Vec::new());
        }
    };
    let catalog = builtin_app_catalog();
    let mut out = Vec::new();
    for c in containers {
        let container_name = c.name.trim_start_matches('/').to_string();
        if !container_name.starts_with(APP_CONTAINER_PREFIX) {
            continue;
        }
        let app_id = container_name
            .strip_prefix(APP_CONTAINER_PREFIX)
            .unwrap_or(&container_name)
            .to_string();
        let entry = catalog.iter().find(|e| e.id == app_id);
        out.push(InstalledApp {
            name: entry.map_or_else(|| app_id.clone(), |e| e.name.clone()),
            web_port: entry.and_then(|e| e.web_port),
            app_id,
            container_id: c.id,
            container_name,
            image: c.image,
            state: c.state,
            status: c.status,
        });
    }
    Ok(out)
}

/// Pulls the image (if missing), creates the host mount directories, and installs a catalog app.
pub async fn install_catalog_app(
    backend: &dyn ContainerBackend,
    cfg: &ContainerConfig,
    req: &AppInstallRequest,
) -> Result<ContainerActionResult> {
    let catalog = builtin_app_catalog();
    let entry = catalog
        .iter()
        .find(|e| e.id == req.app_id)
        .ok_or_else(|| ServiceError::Render(format!("unknown catalog app '{}'", req.app_id)))?;

    let create_req =
        build_app_container_request(entry, req).map_err(|e| ServiceError::Render(e.to_string()))?;

    for mount in &create_req.mounts {
        if let Err(err) = tokio::fs::create_dir_all(&mount.source).await {
            tracing::debug!(path = %mount.source, error = %err, "app mount directory pre-create skipped");
        }
    }

    if entry.id == "mihomo"
        && let Some(cfg_dir) = create_req.mounts.first().map(|m| m.source.as_str())
    {
        seed_mihomo_config_if_missing(cfg_dir, req).await;
    }

    backend.pull_image(cfg, &create_req.image).await?;
    backend.create_container(cfg, &create_req).await
}

async fn seed_mihomo_config_if_missing(cfg_dir: &str, req: &AppInstallRequest) {
    let config_path = std::path::Path::new(cfg_dir).join("config.yaml");
    if config_path.exists() {
        return;
    }
    let web_port = req
        .settings
        .get("web_port")
        .map(String::as_str)
        .map(str::trim)
        .filter(|s| !s.is_empty())
        .unwrap_or("9090");
    let secret = req
        .settings
        .get("secret")
        .map(String::as_str)
        .map_or("", str::trim);
    let initial_yaml = format!(
        "# Generated by CrabRouter App Store\n\
         mixed-port: 7890\n\
         allow-lan: true\n\
         mode: rule\n\
         log-level: info\n\
         external-controller: 0.0.0.0:{web_port}\n\
         secret: \"{secret}\"\n\
         tun:\n  \
           enable: true\n  \
           stack: system\n  \
           auto-route: true\n  \
           auto-detect-interface: true\n"
    );
    if let Err(err) = tokio::fs::write(&config_path, initial_yaml).await {
        tracing::debug!(
            path = %config_path.display(),
            error = %err,
            "skipped seeding initial mihomo config.yaml"
        );
    }
}

/// Starts or stops an installed App Store container.
pub async fn toggle_catalog_app(
    backend: &dyn ContainerBackend,
    cfg: &ContainerConfig,
    app_id: &str,
    start: bool,
) -> Result<ContainerActionResult> {
    let name = app_container_name(app_id);
    let action = if start {
        ContainerAction::Start
    } else {
        ContainerAction::Stop
    };
    backend.container_action(cfg, &name, action).await
}

/// Stops and removes an installed App Store container (preserving `/var` data volumes).
pub async fn uninstall_catalog_app(
    backend: &dyn ContainerBackend,
    cfg: &ContainerConfig,
    app_id: &str,
) -> Result<ContainerActionResult> {
    let name = app_container_name(app_id);
    backend
        .container_action(cfg, &name, ContainerAction::Remove { force: true })
        .await
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeMap;

    use crabrouter_model::{AppInstallRequest, ContainerConfig};

    use super::{install_catalog_app, list_installed_apps, uninstall_catalog_app};
    use crate::containers::dry_run::DryRunContainerBackend;

    #[tokio::test]
    async fn installs_lists_and_uninstalls_catalog_app_in_dry_run() {
        let backend = DryRunContainerBackend::new();
        let cfg = ContainerConfig {
            enabled: true,
            ..ContainerConfig::default()
        };
        let mut settings = BTreeMap::new();
        settings.insert("web_port".to_string(), "5244".to_string());
        let req = AppInstallRequest {
            app_id: "alist".to_string(),
            settings,
            start_immediately: true,
        };
        let res = install_catalog_app(&backend, &cfg, &req)
            .await
            .expect("install app");
        assert!(res.ok);

        let installed = list_installed_apps(&backend, &cfg)
            .await
            .expect("list apps");
        assert_eq!(installed.len(), 1);
        assert_eq!(installed[0].app_id, "alist");

        let rm = uninstall_catalog_app(&backend, &cfg, "alist")
            .await
            .expect("uninstall app");
        assert!(rm.ok);

        let proxy_req = AppInstallRequest {
            app_id: "mihomo".to_string(),
            settings: BTreeMap::new(),
            start_immediately: true,
        };
        let proxy_out = install_catalog_app(&backend, &cfg, &proxy_req)
            .await
            .expect("install mihomo");
        assert!(proxy_out.ok);
    }

    #[tokio::test]
    async fn list_installed_apps_returns_empty_when_disabled_or_socket_unavailable() {
        use crate::containers::socket::SocketContainerBackend;

        let backend = SocketContainerBackend;
        let disabled_cfg = ContainerConfig {
            enabled: false,
            socket_path: "/nonexistent/podman.sock".to_string(),
            ..ContainerConfig::default()
        };
        let apps = list_installed_apps(&backend, &disabled_cfg)
            .await
            .expect("disabled runtime should return empty list");
        assert_eq!(apps.len(), 0);

        let enabled_missing_sock = ContainerConfig {
            enabled: true,
            socket_path: "/nonexistent/podman.sock".to_string(),
            ..ContainerConfig::default()
        };
        let apps = list_installed_apps(&backend, &enabled_missing_sock)
            .await
            .expect("unavailable socket should degrade to empty list");
        assert_eq!(apps.len(), 0);
    }
}
