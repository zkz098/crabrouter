use std::fmt::Write;
use std::fs;
use std::path::Path;

use base64::Engine;
use base64::engine::general_purpose::STANDARD;
use crabrouter_model::RouterConfig;
use serde::Serialize;
use ts_rs::TS;
use x25519_dalek::{PublicKey, StaticSecret};

use crate::{Result, ServiceError};

#[derive(Debug, Clone, Serialize, TS)]
#[ts(export)]
pub struct WireGuardKeypair {
    pub private_key: String,
    pub public_key: String,
}

/// Generates a new Curve25519 `WireGuard` keypair using pure-Rust `x25519-dalek`.
pub fn generate_wireguard_keypair() -> WireGuardKeypair {
    let secret = StaticSecret::random();
    let public = PublicKey::from(&secret);
    WireGuardKeypair {
        private_key: STANDARD.encode(secret.to_bytes()),
        public_key: STANDARD.encode(public.as_bytes()),
    }
}

/// Derives the base64 `WireGuard` public key from a base64-encoded 32-byte private key.
pub fn derive_public_key(private_key_b64: &str) -> Result<String> {
    let raw = STANDARD
        .decode(private_key_b64.trim())
        .map_err(|e| ServiceError::Render(format!("invalid WireGuard private key base64: {e}")))?;
    let bytes: [u8; 32] = raw.try_into().map_err(|_| {
        ServiceError::Render("WireGuard private key must be exactly 32 bytes".to_string())
    })?;
    let secret = StaticSecret::from(bytes);
    let public = PublicKey::from(&secret);
    Ok(STANDARD.encode(public.as_bytes()))
}

/// Renders `/etc/wireguard/<iface>.conf` compatible with `wg-quick` and `wg-quick@.service`.
pub fn render_wg_quick_conf(cfg: &RouterConfig, private_key: &str) -> Result<String> {
    let wg = &cfg.wireguard;
    if wg.interface.trim().is_empty() {
        return Err(ServiceError::Render(
            "wireguard.interface cannot be empty".to_string(),
        ));
    }

    let mut out = String::new();
    let _ = writeln!(
        out,
        "# Generated by crabrouterd — do not edit manually\n\
         [Interface]\n\
         Address = {}\n\
         ListenPort = {}\n\
         PrivateKey = {}\n\
         SaveConfig = false",
        wg.address_cidr,
        wg.listen_port,
        private_key.trim()
    );
    if let Some(mtu) = wg.mtu {
        let _ = writeln!(out, "MTU = {mtu}");
    }

    for peer in &wg.peers {
        let _ = writeln!(out, "\n# Peer: {}", peer.name);
        out.push_str("[Peer]\n");
        let _ = writeln!(out, "PublicKey = {}", peer.public_key.trim());
        let _ = writeln!(out, "AllowedIPs = {}", peer.allowed_ips.join(", "));
        if let Some(endpoint) = peer.endpoint.as_deref().filter(|s| !s.trim().is_empty()) {
            let _ = writeln!(out, "Endpoint = {}", endpoint.trim());
        }
        if let Some(keepalive) = peer.persistent_keepalive {
            let _ = writeln!(out, "PersistentKeepalive = {keepalive}");
        }
    }

    Ok(out)
}

/// Ensures a persistent server private key exists (using `cfg.wireguard.private_key` if set,
/// or reading/creating `<wg_dir>/<iface>.key` with `0600` permissions), writes
/// `<wg_dir>/<iface>.conf` atomically, and returns the derived server public key.
pub fn sync_wireguard_files(cfg: &RouterConfig, wg_dir: &Path) -> Result<String> {
    fs::create_dir_all(wg_dir)?;
    let iface = cfg.wireguard.interface.trim();

    let private_key = if let Some(explicit) = cfg
        .wireguard
        .private_key
        .as_deref()
        .map(str::trim)
        .filter(|s| !s.is_empty())
    {
        explicit.to_string()
    } else {
        let key_path = wg_dir.join(format!("{iface}.key"));
        if key_path.exists() {
            fs::read_to_string(&key_path)?.trim().to_string()
        } else {
            let pair = generate_wireguard_keypair();
            write_secret_file(&key_path, &format!("{}\n", pair.private_key))?;
            pair.private_key
        }
    };

    let public_key = derive_public_key(&private_key)?;
    let conf_content = render_wg_quick_conf(cfg, &private_key)?;
    let conf_path = wg_dir.join(format!("{iface}.conf"));
    write_secret_file(&conf_path, &conf_content)?;
    Ok(public_key)
}

fn write_secret_file(path: &Path, content: &str) -> Result<()> {
    let tmp = path.with_extension("tmp");
    fs::write(&tmp, content)?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        fs::set_permissions(&tmp, fs::Permissions::from_mode(0o600))?;
    }
    fs::rename(&tmp, path)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crabrouter_model::WireGuardPeer;

    #[test]
    fn generates_valid_keypair_and_renders_wg_quick_conf() {
        let pair = generate_wireguard_keypair();
        assert_eq!(
            derive_public_key(&pair.private_key).unwrap(),
            pair.public_key
        );

        let mut cfg = RouterConfig::default();
        cfg.wireguard.enabled = true;
        cfg.wireguard.peers.push(WireGuardPeer {
            name: "laptop".to_string(),
            public_key: generate_wireguard_keypair().public_key,
            allowed_ips: vec!["10.10.0.2/32".to_string()],
            endpoint: None,
            persistent_keepalive: Some(25),
        });

        let conf = render_wg_quick_conf(&cfg, &pair.private_key).unwrap();
        assert!(conf.contains("Address = 10.10.0.1/24"));
        assert!(conf.contains("ListenPort = 51820"));
        assert!(conf.contains("AllowedIPs = 10.10.0.2/32"));
        assert!(conf.contains("PersistentKeepalive = 25"));
    }
}
