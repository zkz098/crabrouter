use std::fmt::Write;

use crabrouter_model::{InterfaceRole, RouterConfig};
use ipnet::IpNet;

/// Renders `/run/crabrouter/chrony.conf` for upstream NTP synchronization and optional LAN NTP server.
pub fn render_chrony_conf(cfg: &RouterConfig) -> String {
    let mut out = String::from("# Generated by crabrouterd — do not edit manually\n");
    for server in &cfg.system.ntp_servers {
        let s = server.trim();
        if !s.is_empty() {
            let _ = writeln!(out, "pool {s} iburst");
        }
    }
    out.push_str("makestep 1.0 3\nrtcsync\ndriftfile /var/lib/chrony/chrony.drift\n");

    if cfg.system.ntp_server_enabled {
        out.push_str("\n# Serve NTP to LAN clients\n");
        for lan in &cfg.lans {
            if let Ok(net) = lan.cidr.parse::<IpNet>() {
                let _ = writeln!(out, "allow {}", net.trunc());
            }
        }
        for vlan in &cfg.vlans {
            if vlan.role == InterfaceRole::Lan
                && let Some(cidr) = vlan.cidr.as_deref()
                && let Ok(net) = cidr.parse::<IpNet>()
            {
                let _ = writeln!(out, "allow {}", net.trunc());
            }
        }
        out.push_str("local stratum 10\n");
    }

    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_chrony_with_optional_lan_server() {
        let mut cfg = RouterConfig::default();
        cfg.system.ntp_server_enabled = true;
        let conf = render_chrony_conf(&cfg);
        assert!(conf.contains("pool pool.ntp.org iburst"));
        assert!(conf.contains("allow 192.168.10.0/24"));
        assert!(conf.contains("local stratum 10"));
    }
}
