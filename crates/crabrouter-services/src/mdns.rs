use std::fmt::Write;

use crabrouter_model::{InterfaceRole, RouterConfig};

/// Renders `avahi-daemon.conf` for cross-VLAN mDNS / Bonjour reflection.
pub fn render_avahi_daemon_conf(cfg: &RouterConfig) -> String {
    if !cfg.mdns.enabled {
        return "# Cross-VLAN mDNS reflection is disabled\n".to_string();
    }

    let ifaces = resolve_mdns_interfaces(cfg);
    let allow_p2p = if cfg.mdns.allow_point_to_point {
        "yes"
    } else {
        "no"
    };
    let publish_ws = if cfg.mdns.publish_workstation {
        "yes"
    } else {
        "no"
    };

    let mut out = String::from("# Generated by crabrouterd — do not edit manually\n[server]\n");
    let _ = writeln!(out, "host-name={}", cfg.system.hostname);
    out.push_str(
        "domain-name=local\n\
         use-ipv4=yes\n\
         use-ipv6=yes\n\
         enable-dbus=no\n",
    );
    if !ifaces.is_empty() {
        let _ = writeln!(out, "allow-interfaces={}", ifaces.join(","));
    }
    let _ = writeln!(out, "disallow-other-stacks=yes");
    let _ = writeln!(
        out,
        "\n[wide-area]\nenable-wide-area=no\n\n\
         [publish]\n\
         publish-addresses=yes\n\
         publish-hinfo=no\n\
         publish-workstation={publish_ws}\n\n\
         [reflector]\n\
         enable-reflector=yes\n\
         reflect-ipv=no\n\n\
         [rlimits]\n\
         rlimit-core=0\n\
         rlimit-data=4194304\n\
         rlimit-fsize=0\n\
         rlimit-nofile=768\n\
         rlimit-stack=4194304\n\
         rlimit-nproc=3\n"
    );
    if cfg.mdns.allow_point_to_point {
        let _ = writeln!(out, "# allow-point-to-point={allow_p2p}");
    }
    out
}

fn resolve_mdns_interfaces(cfg: &RouterConfig) -> Vec<String> {
    if !cfg.mdns.interfaces.is_empty() {
        return cfg
            .mdns
            .interfaces
            .iter()
            .map(|s| s.trim().to_string())
            .filter(|s| !s.is_empty())
            .collect();
    }
    let mut out: Vec<String> = cfg.lans.iter().map(|l| l.bridge.clone()).collect();
    for vlan in &cfg.vlans {
        if vlan.role == InterfaceRole::Lan {
            let name = format!("{}.{}", vlan.parent, vlan.id);
            if !out.contains(&name) {
                out.push(name);
            }
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::render_avahi_daemon_conf;
    use crabrouter_model::RouterConfig;

    #[test]
    fn renders_avahi_reflector_for_lan_bridges_and_vlans() {
        let mut cfg = RouterConfig::default();
        cfg.mdns.enabled = true;
        let rendered = render_avahi_daemon_conf(&cfg);
        assert!(rendered.contains("enable-reflector=yes"));
        assert!(rendered.contains("allow-interfaces=br-lan"));
    }
}
