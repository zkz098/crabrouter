/// Validates and sanitizes an uploaded OTA artifact filename to prevent path traversal.
pub fn sanitize_ota_filename(raw: &str) -> Result<String> {
    let base = Path::new(raw.trim())
        .file_name()
        .and_then(|s| s.to_str())
        .unwrap_or("");
    if base.is_empty()
        || base.contains("..")
        || !base
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '-' | '_'))
    {
        return Err(ServiceError::Render(format!(
            "invalid OTA filename '{raw}'"
        )));
    }
    let lower = base.to_ascii_lowercase();
    let allowed = [".raw", ".raw.xz", ".raw.zst", ".efi", ".img"];
    if !allowed.iter().any(|ext| lower.ends_with(ext)) {
        return Err(ServiceError::Render(format!(
            "unsupported OTA artifact extension for '{base}' (expected .raw, .raw.xz, .raw.zst, .efi, or .img)"
        )));
    }
    Ok(base.to_string())
}

/// Renders a `systemd-sysupdate` `10-root.transfer` definition for either remote HTTPS (`url-file`)
/// or local staged OTA images (`regular-file`).
pub fn render_sysupdate_root_transfer(source: &str, match_pattern: Option<&str>) -> String {
    let src_type = if source.starts_with("http://") || source.starts_with("https://") {
        "url-file"
    } else {
        "regular-file"
    };
    let pattern = match_pattern.unwrap_or("crabrouter_@v.root-x86-64.raw");
    format!(
        "# Generated by crabrouterd — A/B immutable rootfs OTA\n\
         [Transfer]\n\
         ProtectVersion=%A\n\n\
         [Source]\n\
         Type={src_type}\n\
         Path={source}\n\
         MatchPattern={pattern}\n\n\
         [Target]\n\
         Type=partition\n\
         Path=auto\n\
         MatchPattern=crabrouter_root_@v\n\
         PartitionFlags=0\n\
         ReadOnly=1\n"
    )
}

/// Renders `20-uki.transfer` for `systemd-boot` Boot Assessment (`+@t` -> `+3-0` tries counter).
pub fn render_sysupdate_uki_transfer(source: &str) -> String {
    let src_type = if source.starts_with("http://") || source.starts_with("https://") {
        "url-file"
    } else {
        "regular-file"
    };
    format!(
        "# Generated by crabrouterd — UKI kernel update with Boot Assessment\n\
         [Transfer]\n\
         ProtectVersion=%A\n\n\
         [Source]\n\
         Type={src_type}\n\
         Path={source}\n\
         MatchPattern=crabrouter_@v.efi\n\n\
         [Target]\n\
         Type=regular-file\n\
         Path=/EFI/Linux\n\
         PathRelativeTo=boot\n\
         MatchPattern=crabrouter_@v+@t.efi\n\
         TriesLeft=3\n\
         TriesDone=0\n\
         InstancesMax=2\n"
    )
}

pub fn parse_os_release_version(raw: &str) -> Option<String> {
    let mut fallback_version_id = None;
    for line in raw.lines() {
        let trimmed = line.trim();
        if let Some(val) = trimmed.strip_prefix("IMAGE_VERSION=") {
            return Some(val.trim_matches('"').to_string());
        }
        if let Some(val) = trimmed.strip_prefix("VERSION_ID=") {
            fallback_version_id = Some(val.trim_matches('"').to_string());
        }
    }
    fallback_version_id
}

pub fn detect_active_slot(cmdline: &str, mounts: &str) -> Option<String> {
    let combined = format!("{cmdline}\n{mounts}");
    if combined.contains("crabrouter_root_a") {
        return Some("A".to_string());
    }
    if combined.contains("crabrouter_root_b") {
        return Some("B".to_string());
    }
    None
}

pub fn compute_file_sha256(path: &Path) -> Result<String> {
    let mut file = fs::File::open(path)?;
    let mut hasher = Sha256::new();
    let mut buf = vec![0_u8; 64 * 1024];
    loop {
        let n = file.read(&mut buf)?;
        if n == 0 {
            break;
        }
        hasher.update(&buf[..n]);
    }
    Ok(hex::encode(hasher.finalize()))
}

pub fn list_staged_images(ota_dir: &Path) -> Vec<StagedOtaImage> {
    let Ok(entries) = fs::read_dir(ota_dir) else {
        return Vec::new();
    };
    let mut out = Vec::new();
    for entry in entries.flatten() {
        let path = entry.path();
        if !path.is_file() {
            continue;
        }
        let fname = entry.file_name().to_string_lossy().to_string();
        if fname.starts_with('.') || fname == "SHA256SUMS" {
            continue;
        }
        let Ok(meta) = entry.metadata() else {
            continue;
        };
        let modified_at = meta
            .modified()
            .map_or_default(|t| DateTime::<Utc>::from(t).to_rfc3339());
        let sha256 = compute_file_sha256(&path).unwrap_or_else(|_| "error".to_string());
        out.push(StagedOtaImage {
            filename: fname,
            size_bytes: meta.len(),
            sha256,
            modified_at,
        });
    }
    out.sort_by(|a, b| b.modified_at.cmp(&a.modified_at));
    out
}

pub async fn query_ota_status(ota_dir: &Path, source_url: &str, dry_run: bool) -> OtaStatus {
    let current_version = fs::read_to_string("/etc/os-release")
        .ok()
        .and_then(|s| parse_os_release_version(&s));
    let cmdline = fs::read_to_string("/proc/cmdline").unwrap_or_default();
    let mounts = fs::read_to_string("/proc/mounts").unwrap_or_default();
    let active_slot = detect_active_slot(&cmdline, &mounts).or_else(|| {
        if dry_run {
            Some("A (dry-run)".to_string())
        } else {
            None
        }
    });

    let boot_assessment = if dry_run {
        "good (dry-run)".to_string()
    } else {
        query_bless_boot_status().await
    };

    let sysupdate_available = !dry_run && which_exists("systemd-sysupdate").await;
    let staged_images = list_staged_images(ota_dir);

    OtaStatus {
        current_version,
        active_slot,
        boot_assessment,
        sysupdate_available,
        sysupdate_source: source_url.to_string(),
        staged_images,
        available_versions: Vec::new(),
        dry_run,
    }
}

async fn query_bless_boot_status() -> String {
    let mut cmd = Command::new("systemd-bless-boot");
    cmd.arg("status");
    match crate::cmd::run_output_with_timeout(
        &mut cmd,
        std::time::Duration::from_secs(5),
        "systemd-bless-boot status",
    )
    .await
    {
        Ok(out) if out.status.success() => String::from_utf8_lossy(&out.stdout).trim().to_string(),
        Ok(out) => {
            let err = String::from_utf8_lossy(&out.stderr).trim().to_string();
            if err.is_empty() {
                "unavailable".to_string()
            } else {
                err
            }
        }
        Err(_) => "unavailable".to_string(),
    }
}

async fn which_exists(bin: &str) -> bool {
    let mut cmd = Command::new("which");
    cmd.arg(bin);
    crate::cmd::run_output_with_timeout(&mut cmd, std::time::Duration::from_secs(3), "which")
        .await
        .is_ok_and(|o| o.status.success())
}

pub async fn check_ota_updates(
    ota_dir: &Path,
    source_url: &str,
    dry_run: bool,
) -> Result<OtaCommandResult> {
    let staged = list_staged_images(ota_dir);
    if dry_run {
        let mut details = format!("dry-run: configured OTA source = {source_url}\n");
        let _ = writeln!(details, "staged local images ({}):", staged.len());
        for img in &staged {
            let _ = writeln!(
                details,
                "  - {} ({} bytes, sha256={})",
                img.filename, img.size_bytes, img.sha256
            );
        }
        return Ok(OtaCommandResult {
            ok: true,
            action: "check".to_string(),
            message: format!("dry-run check complete ({} staged images)", staged.len()),
            output: details,
            reboot_required: false,
        });
    }

    let mut cmd = Command::new("systemd-sysupdate");
    cmd.arg("list");
    let out = crate::cmd::run_output_with_timeout(
        &mut cmd,
        std::time::Duration::from_secs(30),
        "systemd-sysupdate list",
    )
    .await?;
    let combined = format!(
        "{}\n{}",
        String::from_utf8_lossy(&out.stdout),
        String::from_utf8_lossy(&out.stderr)
    );
    Ok(OtaCommandResult {
        ok: out.status.success(),
        action: "check".to_string(),
        message: if out.status.success() {
            "systemd-sysupdate list completed".to_string()
        } else {
            "systemd-sysupdate list failed".to_string()
        },
        output: combined.trim().to_string(),
        reboot_required: false,
    })
}

pub async fn apply_ota_update(
    ota_dir: &Path,
    source_url: &str,
    staged_file: Option<&str>,
    verify_signature: bool,
    sysupdate_dir: &Path,
    dry_run: bool,
) -> Result<OtaCommandResult> {
    let (resolved_source, match_pattern) = if let Some(fname) = staged_file {
        let safe = sanitize_ota_filename(fname)?;
        let full = ota_dir.join(&safe);
        if !full.exists() {
            return Err(ServiceError::Orchestration(format!(
                "staged OTA image '{}' not found",
                full.display()
            )));
        }
        let dir_str = ota_dir.to_string_lossy().to_string();
        (dir_str, Some(safe))
    } else {
        (source_url.to_string(), None)
    };

    let transfer_root = render_sysupdate_root_transfer(&resolved_source, match_pattern.as_deref());
    let transfer_uki = render_sysupdate_uki_transfer(&resolved_source);

    if dry_run {
        let output = format!(
            "dry-run: rendered systemd-sysupdate transfers (verify={verify_signature}):\n\
             --- 10-root.transfer ---\n{transfer_root}\n\
             --- 20-uki.transfer ---\n{transfer_uki}"
        );
        return Ok(OtaCommandResult {
            ok: true,
            action: "apply".to_string(),
            message: "dry-run: staged A/B OTA update plan validated".to_string(),
            output,
            reboot_required: true,
        });
    }

    fs::create_dir_all(sysupdate_dir)?;
    fs::write(sysupdate_dir.join("10-root.transfer"), transfer_root)?;
    fs::write(sysupdate_dir.join("20-uki.transfer"), transfer_uki)?;

    let mut cmd = Command::new("systemd-sysupdate");
    cmd.arg("update");
    if !verify_signature {
        cmd.arg("--verify=no");
    }
    let out = crate::cmd::run_output_with_timeout(
        &mut cmd,
        std::time::Duration::from_secs(600),
        "systemd-sysupdate update",
    )
    .await?;
    let combined = format!(
        "{}\n{}",
        String::from_utf8_lossy(&out.stdout),
        String::from_utf8_lossy(&out.stderr)
    );
    let ok = out.status.success();
    Ok(OtaCommandResult {
        ok,
        action: "apply".to_string(),
        message: if ok {
            "A/B OTA image written to standby slot; reboot to switch".to_string()
        } else {
            "systemd-sysupdate update failed".to_string()
        },
        output: combined.trim().to_string(),
        reboot_required: ok,
    })
}

pub async fn bless_current_boot(dry_run: bool) -> Result<OtaCommandResult> {
    if dry_run {
        return Ok(OtaCommandResult {
            ok: true,
            action: "bless".to_string(),
            message: "dry-run: marked current boot slot as good (Boot Assessment)".to_string(),
            output: "good (dry-run)".to_string(),
            reboot_required: false,
        });
    }
    let mut cmd = Command::new("systemd-bless-boot");
    cmd.arg("good");
    let out = crate::cmd::run_output_with_timeout(
        &mut cmd,
        std::time::Duration::from_secs(10),
        "systemd-bless-boot good",
    )
    .await?;
    let combined = format!(
        "{}\n{}",
        String::from_utf8_lossy(&out.stdout),
        String::from_utf8_lossy(&out.stderr)
    );
    Ok(OtaCommandResult {
        ok: out.status.success(),
        action: "bless".to_string(),
        message: if out.status.success() {
            "current boot slot blessed as good".to_string()
        } else {
            "systemd-bless-boot good failed".to_string()
        },
        output: combined.trim().to_string(),
        reboot_required: false,
    })
}

/// Automatically marks the current boot slot as good if `systemd-bless-boot status`
/// reports `indeterminate` (first boot after an A/B OTA update) and the daemon passed health checks.
pub async fn auto_bless_if_tentative(dry_run: bool) -> Result<bool> {
    if dry_run {
        return Ok(false);
    }
    let status = query_bless_boot_status().await;
    if status.eq_ignore_ascii_case("indeterminate") {
        let res = bless_current_boot(false).await?;
        if res.ok {
            tracing::info!("auto-blessed tentative OTA boot slot as good");
            return Ok(true);
        }
        tracing::warn!(output = %res.output, "auto-bless of tentative boot slot failed");
    }
    Ok(false)
}

pub async fn trigger_reboot_via_dbus(dry_run: bool) -> Result<OtaCommandResult> {
    if dry_run {
        return Ok(OtaCommandResult {
            ok: true,
            action: "reboot".to_string(),
            message: "dry-run: skipped host reboot via logind D-Bus".to_string(),
            output: "org.freedesktop.login1.Manager.Reboot(false) [dry-run]".to_string(),
            reboot_required: false,
        });
    }
    let conn = zbus::Connection::system()
        .await
        .map_err(|e| ServiceError::Orchestration(format!("system D-Bus connect failed: {e}")))?;
    let proxy = Login1ManagerProxy::new(&conn)
        .await
        .map_err(|e| ServiceError::Orchestration(format!("login1 D-Bus proxy failed: {e}")))?;
    proxy.reboot(false).await.map_err(|e| {
        ServiceError::Orchestration(format!("login1 Reboot D-Bus call failed: {e}"))
    })?;
    Ok(OtaCommandResult {
        ok: true,
        action: "reboot".to_string(),
        message: "system reboot requested via systemd-logind D-Bus".to_string(),
        output: "reboot initiated".to_string(),
        reboot_required: false,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_sysupdate_transfers_and_detects_slot() {
        let remote = render_sysupdate_root_transfer("https://updates.example.com/crabrouter", None);
        assert!(remote.contains("Type=url-file"));
        assert!(remote.contains("ProtectVersion=%A"));

        let local = render_sysupdate_root_transfer(
            "/var/lib/crabrouter/ota",
            Some("crabrouter_0.2.0.root-x86-64.raw"),
        );
        assert!(local.contains("Type=regular-file"));
        assert!(local.contains("MatchPattern=crabrouter_0.2.0.root-x86-64.raw"));

        let uki = render_sysupdate_uki_transfer("https://updates.example.com/crabrouter");
        assert!(uki.contains("TriesLeft=3"));
        assert!(uki.contains("MatchPattern=crabrouter_@v+@t.efi"));

        assert_eq!(
            detect_active_slot("root=PARTLABEL=crabrouter_root_b ro", ""),
            Some("B".to_string())
        );
        assert_eq!(
            parse_os_release_version("NAME=Debian\nIMAGE_VERSION=\"0.2.0\"\n"),
            Some("0.2.0".to_string())
        );
    }

    #[test]
    fn sanitizes_ota_filenames() {
        assert_eq!(
            sanitize_ota_filename("../crabrouter_0.2.0.raw").unwrap(),
            "crabrouter_0.2.0.raw"
        );
        assert!(sanitize_ota_filename("bad;name.sh").is_err());
        assert!(sanitize_ota_filename("malware.exe").is_err());
    }
}
